"use server"

import { sdk } from "@lib/config"
import { HttpTypes } from "@medusajs/types"

import { getAuthHeaders } from "./cookies"

/**
 * Последняя проверка наличия — перед тем как брать деньги.
 *
 * Пока человек выбирал размер и заполнял адрес, последнюю пару могли
 * купить в другом месте: у склада мы не единственный канал, рядом Озон
 * и Вайлдберриз. Остатки приходят раз в минуту, и этой минуты хватает,
 * чтобы продать то, чего уже нет.
 *
 * Поэтому у самой оплаты спрашиваем ещё раз и мимо кэша. Не хватило —
 * говорим об этом до оплаты, а не возвращаем деньги после: возврат для
 * человека хуже, чем честный отказ на минуту раньше.
 *
 * Остаётся окно в несколько секунд между проверкой и оплатой. Закрыть
 * его до нуля можно только бронью на стороне склада; пока договорились,
 * что такие случаи редки и разбираются отказом.
 */
export type Нехватка = {
  название: string
  размер?: string
  просят: number
  осталось: number
}

export type Проверка = {
  хватает: boolean
  нехватка: Нехватка[]
  /** проверка не удалась — пропускаем человека дальше, но отмечаем */
  сбой?: boolean
}

export const проверитьНаличие = async (
  cart: HttpTypes.StoreCart | null
): Promise<Проверка> => {
  const строки = (cart?.items ?? []).filter((i) => i.variant_id)

  if (!строки.length) {
    return { хватает: true, нехватка: [] }
  }

  const идыТоваров = [
    ...new Set(
      строки.map((i) => i.product_id).filter((id): id is string => !!id)
    ),
  ]

  try {
    const { products } = await sdk.client.fetch<{
      products: {
        variants?: {
          id: string
          title?: string
          inventory_quantity?: number
          manage_inventory?: boolean
          allow_backorder?: boolean
        }[]
      }[]
    }>("/store/products", {
      method: "GET",
      query: {
        id: идыТоваров,
        fields: "id,*variants,+variants.inventory_quantity",
        limit: идыТоваров.length,
      },
      headers: { ...(await getAuthHeaders()) },
      // Именно сейчас кэш вреден: мы спрашиваем, чтобы узнать нового,
      // а не чтобы ответить быстро.
      cache: "no-store",
    })

    const поВарианту = new Map<
      string,
      { осталось?: number; считаем: boolean }
    >()

    for (const т of products ?? []) {
      for (const в of т.variants ?? []) {
        поВарианту.set(в.id, {
          осталось: в.inventory_quantity,
          // Размер без поштучного учёта или с дозаказом ограничений не имеет
          считаем: в.manage_inventory !== false && в.allow_backorder !== true,
        })
      }
    }

    const нехватка: Нехватка[] = []

    for (const строка of строки) {
      const про = поВарианту.get(строка.variant_id!)

      // Варианта нет в ответе — не выдумываем, пропускаем: лучше редкий
      // отказ на складе, чем ложное «разобрали» на то, что лежит.
      if (!про || !про.считаем || typeof про.осталось !== "number") {
        continue
      }

      if (про.осталось < строка.quantity) {
        нехватка.push({
          название: строка.product_title ?? строка.title ?? "Товар",
          размер: строка.variant_title ?? undefined,
          просят: строка.quantity,
          осталось: Math.max(0, про.осталось),
        })
      }
    }

    return { хватает: нехватка.length === 0, нехватка }
  } catch (ошибка: any) {
    console.error("Проверка наличия не отработала:", ошибка?.message)
    // Не мешаем покупке из-за своей же поломки: дальше остаток всё
    // равно проверит Medusa, когда будет собирать заказ.
    return { хватает: true, нехватка: [], сбой: true }
  }
}

/** Человеческий текст о том, чего не хватило. */
export const словамиОНехватке = async (
  нехватка: Нехватка[]
): Promise<string> => {
  if (!нехватка.length) {
    return ""
  }

  const части = нехватка.map((н) => {
    const что = н.размер ? `${н.название}, размер ${н.размер}` : н.название
    if (н.осталось === 0) {
      return `${что} — уже разобрали`
    }
    return `${что} — осталось ${н.осталось} шт., а в заказе ${н.просят}`
  })

  const начало =
    нехватка.length === 1
      ? "Пока вы оформляли, товар разобрали:"
      : "Пока вы оформляли, часть товаров разобрали:"

  return `${начало} ${части.join("; ")}. Измените количество в корзине или уберите позицию.`
}
