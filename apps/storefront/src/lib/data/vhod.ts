"use server"

import { sdk } from "@lib/config"
import { revalidateTag } from "next/cache"

import { getCacheTag, setAuthToken } from "./cookies"
import { transferCart } from "./customer"

/**
 * Вход и регистрация по коду из письма. Пароля у покупателя нет.
 *
 * Дверь одна на всех: человек вводит почту и получает код. Что это было,
 * вход или регистрация, выясняется уже после кода — по тому, знаем мы
 * его или нет. Спрашивать заранее «вы у нас впервые?» незачем: человек
 * и сам часто не помнит, заводил он здесь что-нибудь или нет.
 */

export type ШагВхода =
  | { шаг: "почта"; ошибка?: string }
  | { шаг: "код"; почта: string; живёт?: number; ошибка?: string }
  | { шаг: "знакомство"; почта: string; ошибка?: string }
  | { шаг: "готово" }

const ПОХОЖЕ_НА_ПОЧТУ = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/

const текстОшибки = (e: unknown, запасной: string) => {
  const с = String((e as Error)?.message ?? e ?? "")
  // Сообщения Medusa приходят словами внутри длинной строки — вытаскиваем
  // то, что писал наш провайдер, и показываем как есть.
  const наше = с.match(/(Код[^"”\\]*)/)?.[1]
  return наше?.trim() || запасной
}

/** Шаг первый: просим прислать код на почту. */
export async function запроситьКод(почта: string): Promise<ШагВхода> {
  const адрес = почта.trim().toLowerCase()

  if (!ПОХОЖЕ_НА_ПОЧТУ.test(адрес)) {
    return { шаг: "почта", ошибка: "Кажется, в адресе опечатка. Пример: anna@mail.ru" }
  }

  try {
    const ответ = await sdk.client.fetch<{ отправлено: boolean; живёт: number }>(
      "/store/vhod",
      { method: "POST", body: { email: адрес } }
    )
    return { шаг: "код", почта: адрес, живёт: ответ?.живёт ?? 10 }
  } catch (e: any) {
    // Слишком частый запрос — единственный случай, когда мы говорим
    // правду про адрес; про остальное молчим, чтобы перебором нельзя
    // было выяснить, кто у нас покупает.
    const тело = e?.response?.data ?? {}
    if (тело?.ошибка) {
      return { шаг: "почта", ошибка: String(тело.ошибка) }
    }
    return {
      шаг: "почта",
      ошибка: "Не получилось отправить письмо. Попробуйте ещё раз.",
    }
  }
}

/**
 * Шаг второй: проверяем код.
 *
 * Успех ещё не значит, что человек у нас есть: личность заводится при
 * первом же входе, а карточка покупателя — только когда он назовёт имя.
 * Поэтому здесь и выясняется, знакомимся мы или встречаем своего.
 */
export async function войтиПоКоду(
  почта: string,
  код: string
): Promise<ШагВхода> {
  const адрес = почта.trim().toLowerCase()
  const чистый = код.replace(/\D/g, "")

  if (!чистый) {
    return { шаг: "код", почта: адрес, ошибка: "Введите код из письма" }
  }

  let ключ: string
  try {
    const ответ = await sdk.auth.login("customer", "kod", {
      email: адрес,
      code: чистый,
    })
    if (typeof ответ !== "string") {
      return { шаг: "код", почта: адрес, ошибка: "Этот способ входа не поддерживается" }
    }
    ключ = ответ
  } catch (e) {
    return { шаг: "код", почта: адрес, ошибка: текстОшибки(e, "Код не подошёл") }
  }

  // Ключ кладём сразу: он привязан к личности и без карточки покупателя
  // почти ничего не даёт, зато следующим шагом с ним можно её завести.
  await setAuthToken(ключ)

  const знаем = await sdk.store.customer
    .retrieve({}, { authorization: `Bearer ${ключ}` })
    .then(() => true)
    .catch(() => false)

  if (!знаем) {
    return { шаг: "знакомство", почта: адрес }
  }

  await послеВхода()
  return { шаг: "готово" }
}

/** Шаг третий, только для новых: как к вам обращаться. */
export async function завершитьЗнакомство(
  почта: string,
  поля: { фамилия: string; имя: string; возраст?: string }
): Promise<ШагВхода> {
  const адрес = почта.trim().toLowerCase()
  const фамилия = поля.фамилия.trim()
  const имя = поля.имя.trim()

  if (!фамилия || !имя) {
    return { шаг: "знакомство", почта: адрес, ошибка: "Нужны имя и фамилия" }
  }

  const возраст = поля.возраст?.trim()
  if (возраст && !/^\d{1,3}$/.test(возраст)) {
    return { шаг: "знакомство", почта: адрес, ошибка: "Возраст — числом, например 34" }
  }

  try {
    await sdk.store.customer.create({
      email: адрес,
      first_name: имя,
      last_name: фамилия,
      ...(возраст ? { metadata: { возраст: Number(возраст) } } : {}),
    })

    // Прежний ключ выписан на личность без покупателя. Меняем его на
    // свежий: иначе запросы «мои заказы» и «мой профиль» будут отлетать.
    const свежий = await sdk.auth.refresh()
    if (typeof свежий === "string") {
      await setAuthToken(свежий)
    }
  } catch (e) {
    return {
      шаг: "знакомство",
      почта: адрес,
      ошибка: текстОшибки(e, "Не получилось сохранить. Попробуйте ещё раз."),
    }
  }

  await послеВхода()
  return { шаг: "готово" }
}

/** Общий хвост: обновить кеш и перенести корзину гостя на покупателя. */
async function послеВхода() {
  revalidateTag(await getCacheTag("customers"))
  try {
    await transferCart()
  } catch {
    // Корзина не перенеслась — вход всё равно состоялся, не мешаем.
  }
}
