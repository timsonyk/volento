import { listProducts } from "./products"

/**
 * Картинки и надписи главной страницы.
 *
 * Всё лежит в метаданных служебной записи админки «Оформление сайта»
 * (адрес home-banner, метка system) и правится на своей странице админки —
 * «Главная» в левом меню.
 *
 * У каждого места свой ключ; порядок картинок в блоке «Медиа» ни на что не
 * влияет. Так было не всегда: раньше место определялось номером картинки,
 * и чтобы поменять плитку раздела, приходилось считать до шестой. Ключи
 * заполняются миграцией в scripts/setup-banner.js.
 *
 * Ключи картинок:
 *   верх_телефон, верх_компьютер — первый экран
 *   низ_телефон, низ_компьютер   — баннер в конце
 *   середина                     — между разделами и низом
 *   плитка_<адрес раздела>       — плитка раздела на главной
 *
 * Ключи надписей:
 *   надпись, ссылка_текст, ссылка_адрес — поверх верхнего баннера
 *   акция_текст, акция_показывать       — полоса над шапкой
 *
 * Реквизиты продавца (для политики обработки данных и оферты):
 *   юр_наименование, юр_инн, юр_огрн, юр_адрес, юр_почта
 * Пока они пустые, юридические страницы не открываются и в меню их нет:
 *政策 без реквизитов юридической силы не имеет, а вводить покупателя
 * в заблуждение хуже, чем не показать страницу вовсе.
 */
export type ГлавнаяСтраница = {
  картинка: (ключ: string) => string | undefined
  надпись?: string
  ссылкаТекст?: string
  ссылкаАдрес: string
  акцияТекст?: string
  акцияПоказывать: boolean
  реквизиты?: Реквизиты
}

/** Реквизиты продавца. Без них юридические страницы не показываются. */
export type Реквизиты = {
  наименование: string
  инн: string
  огрн?: string
  адрес: string
  почта: string
}

const BANNER_HANDLE = "home-banner"

const строка = (v: unknown) =>
  typeof v === "string" && v.trim() ? v.trim() : undefined

export async function getHomeContent(
  countryCode: string
): Promise<ГлавнаяСтраница> {
  let m: Record<string, unknown> = {}

  try {
    const {
      response: { products },
    } = await listProducts({
      countryCode,
      queryParams: { handle: BANNER_HANDLE, limit: 1 },
    })
    m = (products[0]?.metadata ?? {}) as Record<string, unknown>
  } catch {
    // не критично: при недоступном бэкенде блоки покажут запасные картинки
  }

  return {
    картинка: (ключ) => строка(m[ключ]),
    надпись: строка(m["надпись"]),
    ссылкаТекст: строка(m["ссылка_текст"]),
    ссылкаАдрес: строка(m["ссылка_адрес"]) ?? "/store",
    акцияТекст: строка(m["акция_текст"]),
    // выключается любым внятным «нет»; всё остальное считаем «да»
    акцияПоказывать: !["нет", "no", "false", "0"].includes(
      (строка(m["акция_показывать"]) ?? "да").toLowerCase()
    ),
    реквизиты: собратьРеквизиты(m),
  }
}

/**
 * Реквизиты считаются заполненными, только если есть всё обязательное:
 * половина реквизитов в договоре хуже, чем их отсутствие.
 */
function собратьРеквизиты(m: Record<string, unknown>): Реквизиты | undefined {
  const наименование = строка(m["юр_наименование"])
  const инн = строка(m["юр_инн"])
  const адрес = строка(m["юр_адрес"])
  const почта = строка(m["юр_почта"])

  if (!наименование || !инн || !адрес || !почта) {
    return undefined
  }

  return { наименование, инн, огрн: строка(m["юр_огрн"]), адрес, почта }
}

/** Ключ плитки раздела — такой же, как в админке. */
export const ключПлитки = (адрес: string) => `плитка_${адрес}`
