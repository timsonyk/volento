import { listProducts } from "./products"

/**
 * Картинки главной страницы. Все лежат в одной служебной записи админки
 * «Картинки главной страницы» (адрес home-banner, метка system) — Medusa
 * не хранит произвольные картинки сайта, зато хорошо хранит изображения
 * товара, и админка даёт готовый интерфейс загрузки.
 *
 * Порядок картинок в записи и есть настройка:
 *   1 — верхний баннер, телефон: вертикальная 4:5, 1080x1350
 *   2 — верхний баннер, компьютер: широкая 8:5, 2560x1600
 *   3 — нижний баннер, телефон: вертикальная 4:5, 1080x1350
 *   4 — нижний баннер, компьютер: широкая 16:9, 2560x1440
 *   5 — широкая картинка в середине: на телефоне квадрат, от планшета
 *       16:9, исходник 2560x1440
 *
 * Возвращает адреса по номерам; если картинки нет — undefined, каждый
 * блок сам решает, чем её заменить.
 */
const BANNER_HANDLE = "home-banner"

export async function getHomeImages(
  countryCode: string
): Promise<(string | undefined)[]> {
  try {
    const {
      response: { products },
    } = await listProducts({
      countryCode,
      queryParams: { handle: BANNER_HANDLE, limit: 1 },
    })
    return (products[0]?.images ?? []).map((i) => i.url || undefined)
  } catch {
    // картинки не критичны: при недоступном бэкенде блоки покажут запасные
    return []
  }
}
