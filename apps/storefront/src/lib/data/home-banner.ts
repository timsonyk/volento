import { listProducts } from "./products"

/**
 * Картинки и надпись главной страницы. Всё лежит в одной служебной записи
 * админки «Картинки главной страницы» (адрес home-banner, метка system):
 * Medusa не хранит произвольные картинки сайта, зато хорошо хранит
 * изображения товара, и админка даёт готовый интерфейс загрузки.
 *
 * Порядок картинок в записи и есть настройка:
 *   1 — верхний баннер: телефон целиком и левая половина на компьютере,
 *       вертикальная 4:5, 1080x1350
 *   2 — верхний баннер, правая половина на компьютере, тоже 4:5
 *   3 — нижний баннер, телефон: вертикальная 4:5
 *   4 — нижний баннер, компьютер: широкая 16:9, 2560x1440
 *   5 — широкая картинка в середине: телефон квадрат, дальше 16:9
 *
 * Надпись поверх верхнего баннера редактируется там же, в блоке
 * «Метаданные» записи, ключами:
 *   надпись        — крупный текст
 *   ссылка_текст   — подпись ссылки под ним
 *   ссылка_адрес   — куда ведёт, по умолчанию /store
 * Пустая надпись — баннер показывается чистым.
 */
export type ГлавнаяСтраница = {
  картинки: (string | undefined)[]
  надпись?: string
  ссылкаТекст?: string
  ссылкаАдрес: string
}

const BANNER_HANDLE = "home-banner"

const строка = (v: unknown) =>
  typeof v === "string" && v.trim() ? v.trim() : undefined

export async function getHomeContent(
  countryCode: string
): Promise<ГлавнаяСтраница> {
  try {
    const {
      response: { products },
    } = await listProducts({
      countryCode,
      queryParams: { handle: BANNER_HANDLE, limit: 1 },
    })
    const p = products[0]
    const m = (p?.metadata ?? {}) as Record<string, unknown>
    return {
      картинки: (p?.images ?? []).map((i) => i.url || undefined),
      надпись: строка(m["надпись"]),
      ссылкаТекст: строка(m["ссылка_текст"]),
      ссылкаАдрес: строка(m["ссылка_адрес"]) ?? "/store",
    }
  } catch {
    // не критично: при недоступном бэкенде блоки покажут запасные картинки
    return { картинки: [], ссылкаАдрес: "/store" }
  }
}

/** Только адреса картинок — для блоков, которым надпись не нужна. */
export async function getHomeImages(countryCode: string) {
  return (await getHomeContent(countryCode)).картинки
}
