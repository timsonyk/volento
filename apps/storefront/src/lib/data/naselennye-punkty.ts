"use server"

import данные from "./naselennye-punkty.json"

/**
 * Посёлки, деревни и сёла рядом с городами, куда мы возим.
 *
 * Человек из Кудрова или Шушар ищет свой посёлок, а пункты выдачи у служб
 * числятся за Санкт-Петербургом. Список собирает scripts/collect-settlements.py:
 * населённые пункты из OpenStreetMap, к каждому — ближайший город с
 * пунктами выдачи (по координатам самих пунктов).
 *
 * Список большой — несколько мегабайт, поэтому ищем на сервере, а в
 * браузер уходят только найденные строки.
 */
type Данные = {
  goroda: string[]
  regiony: string[]
  /** [название, номер региона, номер города] */
  punkty: [string, number, number][]
}

export type НаселённыйПункт = {
  имя: string
  регион: string
  город: string
}

const { goroda, regiony, punkty } = данные as Данные

const СКОЛЬКО = 6

// «Орёл» и «Орел» — одно и то же: на телефоне «ё» почти никто не ищет
const обычный = (с: string) => с.trim().toLowerCase().replace(/ё/g, "е")

const ИМЕНА = punkty.map(([имя]) => обычный(имя))

export const найтиНаселённыйПункт = async (
  запрос: string
): Promise<НаселённыйПункт[]> => {
  const з = обычный(запрос)
  if (з.length < 2) {
    return []
  }

  // Список отсортирован от крупных к мелким: сначала те, что начинаются
  // с введённого, а «содержат» — только если первых не хватило
  const начинаются: number[] = []
  const содержат: number[] = []

  for (let и = 0; и < ИМЕНА.length && начинаются.length < СКОЛЬКО; и++) {
    const имя = ИМЕНА[и]
    if (имя.startsWith(з)) {
      начинаются.push(и)
    } else if (содержат.length < СКОЛЬКО && имя.includes(з)) {
      содержат.push(и)
    }
  }

  return [...начинаются, ...содержат].slice(0, СКОЛЬКО).map((и) => {
    const [имя, регион, город] = punkty[и]
    return { имя, регион: regiony[регион], город: goroda[город] }
  })
}
