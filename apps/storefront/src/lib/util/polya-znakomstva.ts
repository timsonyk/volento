/**
 * Разбор и приведение полей знакомства: дата рождения и телефон.
 *
 * Вынесено отдельно, потому что нужно с двух сторон: на экране, чтобы
 * подставлять точки и скобки по мере набора, и на сервере, чтобы не
 * поверить на слово присланному с витрины.
 */

/** Самый старый покупатель, которого мы готовы считать настоящим. */
const ПРЕДЕЛЬНЫЙ_ВОЗРАСТ = 120

/** Младше этого заказ оформлять не может. */
const МЛАДШИЙ_ВОЗРАСТ = 14

/**
 * Ставит точки по мере набора: 12 → «12», 1205 → «12.05».
 *
 * Хвостовую точку не дописываем нарочно: с ней нельзя стереть последнюю
 * цифру — точка возвращалась бы на место при каждом нажатии.
 */
export const сТочками = (ввод: string): string => {
  const цифры = ввод.replace(/\D/g, "").slice(0, 8)
  return [цифры.slice(0, 2), цифры.slice(2, 4), цифры.slice(4, 8)]
    .filter(Boolean)
    .join(".")
}

export type РазборДаты =
  | { годится: true; ISO: string; показать: string }
  | { годится: false; ошибка: string }

/** Проверяет дату по-настоящему: 31 февраля не существует. */
export const разобратьДату = (ввод: string): РазборДаты => {
  const цифры = ввод.replace(/\D/g, "")
  if (цифры.length !== 8) {
    return { годится: false, ошибка: "Дата рождения — днём, месяцем и годом: 12.05.1990" }
  }

  const день = Number(цифры.slice(0, 2))
  const месяц = Number(цифры.slice(2, 4))
  const год = Number(цифры.slice(4, 8))

  const дата = new Date(Date.UTC(год, месяц - 1, день))
  const настоящая =
    дата.getUTCFullYear() === год &&
    дата.getUTCMonth() === месяц - 1 &&
    дата.getUTCDate() === день

  if (!настоящая) {
    return { годится: false, ошибка: "Такой даты не бывает. Проверьте день и месяц." }
  }

  const сейчас = new Date()
  if (дата.getTime() > сейчас.getTime()) {
    return { годится: false, ошибка: "Дата рождения в будущем" }
  }

  let лет = сейчас.getUTCFullYear() - год
  const былДеньРождения =
    сейчас.getUTCMonth() > месяц - 1 ||
    (сейчас.getUTCMonth() === месяц - 1 && сейчас.getUTCDate() >= день)
  if (!былДеньРождения) лет--

  if (лет > ПРЕДЕЛЬНЫЙ_ВОЗРАСТ) {
    return { годится: false, ошибка: "Проверьте год рождения" }
  }
  if (лет < МЛАДШИЙ_ВОЗРАСТ) {
    return { годится: false, ошибка: `Заказ можно оформить с ${МЛАДШИЙ_ВОЗРАСТ} лет` }
  }

  const дв = (n: number) => String(n).padStart(2, "0")
  return {
    годится: true,
    // Храним годом-месяцем-днём: так дату можно сравнивать и сортировать,
    // а показываем привычно, через точки.
    ISO: `${год}-${дв(месяц)}-${дв(день)}`,
    показать: `${дв(день)}.${дв(месяц)}.${год}`,
  }
}

/**
 * Приводит телефон к привычному виду по мере набора.
 *
 * Российский номер разбиваем пробелами и дефисами; всё остальное
 * оставляем как есть — заграничные номера бывают любой длины, и
 * навязанная им маска только мешает.
 */
export const телефономСМаской = (ввод: string): string => {
  const заграничный = ввод.trim().startsWith("+") && !/^\+7/.test(ввод.trim())
  if (заграничный) {
    return "+" + ввод.replace(/[^\d]/g, "").slice(0, 15)
  }

  let цифры = ввод.replace(/\D/g, "")
  if (цифры.startsWith("8")) цифры = "7" + цифры.slice(1)
  if (цифры && !цифры.startsWith("7")) цифры = "7" + цифры
  цифры = цифры.slice(0, 11)

  if (!цифры) return ""

  const части = [
    "+7",
    цифры.slice(1, 4),
    цифры.slice(4, 7),
    цифры.slice(7, 9),
    цифры.slice(9, 11),
  ].filter(Boolean)

  const [код, а, б, в, г] = части
  return [код, а, б, в && г ? `${в}-${г}` : в].filter(Boolean).join(" ")
}

export type РазборТелефона =
  | { годится: true; значение: string }
  | { годится: false; ошибка: string }

export const разобратьТелефон = (ввод: string): РазборТелефона => {
  const чистый = ввод.trim()
  if (!чистый) {
    return { годится: false, ошибка: "Телефон нужен: по нему звонит курьер" }
  }

  const цифры = чистый.replace(/\D/g, "")

  if (чистый.startsWith("+") && !чистый.startsWith("+7")) {
    return цифры.length >= 8 && цифры.length <= 15
      ? { годится: true, значение: "+" + цифры }
      : { годится: false, ошибка: "Проверьте номер" }
  }

  const наши = цифры.startsWith("8") ? "7" + цифры.slice(1) : цифры
  if (наши.length !== 11 || !наши.startsWith("7")) {
    return { годится: false, ошибка: "В номере должно быть 11 цифр: +7 900 123-45-67" }
  }
  return { годится: true, значение: "+" + наши }
}
