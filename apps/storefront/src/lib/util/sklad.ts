/**
 * Ответы склада — по-русски и по делу.
 *
 * Medusa отвечает на нехватку остатка английской фразой «Some variant
 * does not have the required inventory». Показывать её покупателю нельзя:
 * она на чужом языке и не говорит, что делать. Переводим и, если знаем
 * остаток, сразу называем, сколько есть.
 */
const НЕТ_ОСТАТКА = /required inventory|insufficient.?inventory/i

const штук = (n: number) => {
  const две = n % 100
  if (две >= 11 && две <= 14) return "штук"
  const одна = n % 10
  if (одна === 1) return "штука"
  if (одна >= 2 && одна <= 4) return "штуки"
  return "штук"
}

export const поЧеловечески = (
  сообщение: string,
  осталось?: number | null
): string => {
  if (!НЕТ_ОСТАТКА.test(сообщение)) {
    return сообщение
  }
  if (typeof осталось === "number" && осталось > 0) {
    return `Столько нет в наличии: осталось ${осталось} ${штук(осталось)}.`
  }
  return "Этого размера уже нет в наличии."
}
