/**
 * Текст сбоя для покупателя.
 *
 * Ошибка от сервера или сети приходит по-английски: «Failed to fetch»,
 * «An error occurred in the Server Components render…». Показывать это
 * покупателю нельзя. Русский текст (его пишем мы сами) оставляем как
 * есть, всё остальное меняем на общий понятный.
 */
export const НЕТ_СВЯЗИ =
  "Не получилось связаться с магазином. Проверьте интернет и попробуйте ещё раз"

export const текстСбоя = (ошибка: unknown, запасной: string = НЕТ_СВЯЗИ): string => {
  const текст =
    ошибка instanceof Error ? ошибка.message : typeof ошибка === "string" ? ошибка : ""
  return /[а-яё]/i.test(текст) ? текст : запасной
}
