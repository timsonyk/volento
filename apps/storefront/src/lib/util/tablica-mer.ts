import "server-only"

import { HttpTypes } from "@medusajs/types"
import { unstable_cache } from "next/cache"
import sharp from "sharp"

/**
 * Таблица мерок — последний снимок товара с Ozon: белый лист с сеткой и
 * цифрами. В галерее она выглядела обрезанной фотографией, поэтому её
 * показываем отдельно, по кнопке «Таблица размеров» у выбора размера
 * (встреча 23 октября).
 *
 * Пометки «это таблица» у снимков нет, а заводить её руками на каждый из
 * четырёхсот товаров никто не будет. Поэтому узнаём сами: таблица — это
 * последний снимок, на котором есть линии сетки во всю ширину и высоту
 * кадра, а сам кадр в основном белый. У фотографий таких линий не бывает,
 * даже на белом фоне. Правило проверено на всём каталоге: 296 таблиц из
 * 390 товаров, ни одной фотографии по ошибке (23 октября 2026).
 *
 * Снимок разбираем один раз: ответ запоминается. Не скачалось или не
 * разобралось — считаем фотографией: лишняя таблица в галерее лучше
 * пропавшего снимка.
 */
const ШИРИНА = 800

async function разобрать(url: string): Promise<boolean> {
  try {
    const ответ = await fetch(url, { signal: AbortSignal.timeout(8000), cache: "no-store" })
    if (!ответ.ok) return false
    const { data, info } = await sharp(Buffer.from(await ответ.arrayBuffer()))
      .resize(ШИРИНА)
      .grayscale()
      .raw()
      .toBuffer({ resolveWithObject: true })
    const { width: w, height: h } = info
    const тёмный = (i: number) => data[i] < 160

    // линии во всю ширину: строки, где тёмного больше половины
    let гор = 0
    let белых = 0
    let была = false
    for (let y = 0; y < h; y++) {
      let т = 0
      for (let x = 0; x < w; x++) {
        const i = y * w + x
        if (тёмный(i)) т++
        if (data[i] > 225) белых++
      }
      const линия = т / w > 0.5
      if (линия && !была) гор++
      была = линия
    }

    // и во всю высоту
    let верт = 0
    была = false
    for (let x = 0; x < w; x++) {
      let т = 0
      for (let y = 0; y < h; y++) if (тёмный(y * w + x)) т++
      const линия = т / h > 0.45
      if (линия && !была) верт++
      была = линия
    }

    const бел = белых / (w * h)
    // сетка; или таблица только с горизонтальными линиями — тогда их много
    return (гор >= 6 && верт >= 4 && бел >= 0.6) || (гор >= 10 && бел >= 0.8)
  } catch {
    return false
  }
}

const этоТаблица = unstable_cache(разобрать, ["tablica-mer-v1"], { revalidate: false })

/** Делит снимки товара на фотографии и таблицу мерок. */
export async function разделитьСнимки(
  снимки: HttpTypes.StoreProductImage[]
): Promise<{ фото: HttpTypes.StoreProductImage[]; таблицы: string[] }> {
  const последний = снимки[снимки.length - 1]
  // единственный снимок не трогаем: без фотографий карточка пустая
  if (снимки.length < 2 || !последний?.url || !(await этоТаблица(последний.url))) {
    return { фото: снимки, таблицы: [] }
  }
  return { фото: снимки.slice(0, -1), таблицы: [последний.url] }
}
