/**
 * Поиск по каталогу, понимающий человеческий запрос.
 *
 * Встроенный поиск Medusa ищет слово как есть: «черные брюки» не находил
 * ничего (в названиях «черный»), «чёрный» — тоже (в каталоге через «е»),
 * «юбки» давал пять товаров вместо девятнадцати. Здесь запрос разбирается
 * на слова, у слов срезаются окончания, и каждое слово должно начинать
 * какое-нибудь слово из сведений о товаре: названия, цвета, вида, ткани,
 * раздела, артикула.
 */

export type ТоварДляПоиска = {
  id: string
  title?: string | null
  metadata?: Record<string, unknown> | null
  categories?: { name?: string }[] | null
}

/** Поля сведений о товаре, по которым ищем (кроме названия и разделов). */
const ПОЛЯ = ["color", "kind", "gender", "tkan", "fabric", "cut", "style", "model", "article"]

/** Слова, которые ничего не уточняют. */
const ПУСТЫЕ = new Set([
  "и", "в", "с", "на", "для", "под", "из", "по", "от", "до", "или",
  // «арт 6120», «артикул 6120»: само слово в сведениях о товаре не стоит
  "арт", "артикул", "артикула", "art",
])

const ОКОНЧАНИЯ = [
  "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
  "ая", "яя", "ое", "ее", "ые", "ие", "ый", "ий", "ой", "ую", "юю",
  "ых", "их", "ым", "им", "ом", "ем", "ах", "ях", "ов", "ев", "ам", "ям",
  "а", "я", "ы", "и", "у", "ю", "е", "о", "ь",
]

/** Строчные буквы, «ё» как «е», всё лишнее — в пробелы. */
export const привести = (текст: string) =>
  текст
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/g, " ")
    .trim()

/** Основа слова: без окончания, но не короче трёх букв. Числа не трогаем. */
export const основа = (слово: string) => {
  if (/\d/.test(слово) || слово.length < 4) {
    return слово
  }
  for (const о of ОКОНЧАНИЯ) {
    if (слово.endsWith(о) && слово.length - о.length >= 3) {
      return слово.slice(0, -о.length)
    }
  }
  return слово
}

const ЛАТИНИЦА = "qwertyuiop[]asdfghjkl;'zxcvbnm,.`"
const КИРИЛЛИЦА = "йцукенгшщзхъфывапролджэячсмитьбюё"

/** «,h.rb» — это «брюки», набранные в английской раскладке. */
export const изДругойРаскладки = (текст: string) =>
  текст
    .toLowerCase()
    .split("")
    .map((б) => {
      const i = ЛАТИНИЦА.indexOf(б)
      return i >= 0 ? КИРИЛЛИЦА[i] : б
    })
    .join("")

const ТРАНСЛИТ: [string, string][] = [
  ["shch", "щ"], ["sch", "щ"], ["zh", "ж"], ["kh", "х"], ["ts", "ц"], ["ch", "ч"],
  ["sh", "ш"], ["yu", "ю"], ["ju", "ю"], ["ya", "я"], ["ja", "я"], ["yo", "е"],
  ["a", "а"], ["b", "б"], ["v", "в"], ["g", "г"], ["d", "д"], ["e", "е"],
  ["z", "з"], ["i", "и"], ["j", "й"], ["k", "к"], ["l", "л"], ["m", "м"],
  ["n", "н"], ["o", "о"], ["p", "п"], ["r", "р"], ["s", "с"], ["t", "т"],
  ["u", "у"], ["f", "ф"], ["h", "х"], ["c", "к"], ["y", "ы"], ["w", "в"],
  ["x", "кс"], ["q", "к"],
]

/** «bryuki», «yubka» — русские слова латиницей (телефон без русской раскладки). */
export const изЛатиницы = (текст: string) => {
  let итог = ""
  const т = текст.toLowerCase()
  for (let i = 0; i < т.length; ) {
    const пара = ТРАНСЛИТ.find(([лат]) => т.startsWith(лат, i))
    итог += пара ? пара[1] : т[i]
    i += пара ? пара[0].length : 1
  }
  return итог
}

/**
 * Слова, которых в каталоге нет, но ищут ими то же самое. Ключ и
 * значение записаны основами.
 */
const СИНОНИМЫ: Record<string, string> = {
  штан: "брюк",
  штаник: "брюк",
  штанишк: "брюк",
  сорочк: "рубашк",
  кофт: "блуз",
  кофточк: "блуз",
}

/** Слова запроса, уже основами. Артикул «3149-46/170» даёт «3149». */
export const словаЗапроса = (запрос: string): string[] => {
  // размер и рост в артикуле товар не уточняют: у всех размеров он один
  const безРазмера = запрос.replace(/(\d{3,})-\d+(\/\d+)?/g, "$1")
  return привести(безРазмера)
    .split(" ")
    .filter((с) => с && !ПУСТЫЕ.has(с))
    .map(основа)
    .map((с) => СИНОНИМЫ[с] ?? с)
}

/** Отличаются не больше чем одной буквой: заменой, пропуском или лишней. */
const однаОшибка = (а: string, б: string) => {
  if (Math.abs(а.length - б.length) > 1) {
    return false
  }
  let i = 0
  while (i < а.length && i < б.length && а[i] === б[i]) {
    i++
  }
  if (а.length === б.length) {
    return а.slice(i + 1) === б.slice(i + 1)
  }
  const [длинное, короткое] = а.length > б.length ? [а, б] : [б, а]
  return длинное.slice(i + 1) === короткое.slice(i)
}

/**
 * Слово запроса с опечаткой: «юпка», «блуска», «брбки». Первая буква
 * должна совпасть, иначе короткие слова начинают находить что попало.
 */
const похоже = (слово: string, изТовара: string) => {
  if (слово.length < 3 || /\d/.test(слово) || слово[0] !== изТовара[0]) {
    return false
  }
  for (const длина of [слово.length - 1, слово.length, слово.length + 1]) {
    if (длина >= 2 && однаОшибка(слово, изТовара.slice(0, длина))) {
      return true
    }
  }
  return false
}

const словаТовара = (т: ТоварДляПоиска): string[] => {
  const части: string[] = [т.title ?? ""]
  for (const поле of ПОЛЯ) {
    const з = т.metadata?.[поле]
    if (typeof з === "string") {
      части.push(з)
    }
  }
  for (const к of т.categories ?? []) {
    части.push(к.name ?? "")
  }
  return привести(части.join(" ")).split(" ").filter(Boolean)
}

const отобрать = (
  товары: ТоварДляПоиска[],
  слова: string[],
  сОпечатками = false
) =>
  товары
    .filter((т) => {
      const есть = словаТовара(т)
      return слова.every((с) =>
        есть.some((е) => е.startsWith(с) || (сОпечатками && похоже(с, е)))
      )
    })
    .map((т) => т.id)

/**
 * id товаров, подходящих под запрос. Если точно ничего не нашлось,
 * пробуем по очереди:
 * 1) прочитать запрос как набранный не в той раскладке;
 * 2) простить по одной опечатке в слове и не требовать чисел: «брюки 44»
 *    это брюки, размер выбирают уже в товаре, в сведениях о товаре его нет.
 */
export const найтиПоСловам = (товары: ТоварДляПоиска[], запрос: string): string[] => {
  const слова = словаЗапроса(запрос)
  if (!слова.length) {
    return []
  }

  const найдено = отобрать(товары, слова)
  if (найдено.length) {
    return найдено
  }

  if (/[a-z,.;'\[\]`]/i.test(запрос)) {
    const иначе = словаЗапроса(изДругойРаскладки(запрос))
    const поРаскладке = иначе.length ? отобрать(товары, иначе) : []
    if (поРаскладке.length) {
      return поРаскладке
    }
  }

  const безЧисел = слова.filter((с) => !/^\d{1,3}$/.test(с))
  const сОпечатками = безЧисел.length ? отобрать(товары, безЧисел, true) : []
  if (сОпечатками.length || !/[a-z]/i.test(запрос)) {
    return сОпечатками
  }

  // 3) русские слова латиницей: «bryuki», «bruki», «yubka chernaya»
  const латиницей = словаЗапроса(изЛатиницы(запрос)).filter((с) => !/^\d{1,3}$/.test(с))
  if (!латиницей.length) {
    return []
  }
  const точно = отобрать(товары, латиницей)
  if (точно.length) {
    return точно
  }
  // Опечатку прощаем только длинным словам: короткое чужое слово («zara»
  // даёт «зар») с одной заменой буквы находило что попало.
  return латиницей.every((с) => с.length >= 4) ? отобрать(товары, латиницей, true) : []
}
