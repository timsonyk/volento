/**
 * Поиск по каталогу, понимающий человеческий запрос.
 *
 * Встроенный поиск Medusa ищет слово как есть: «черные брюки» не находил
 * ничего (в названиях «черный»), «чёрный» — тоже (в каталоге через «е»),
 * «юбки» давал пять товаров вместо девятнадцати. Здесь запрос разбирается
 * на слова, у слов срезаются окончания, и каждое слово должно начинать
 * какое-нибудь слово из сведений о товаре: названия, цвета, вида, ткани,
 * раздела, артикула.
 */

export type ТоварДляПоиска = {
  id: string
  title?: string | null
  metadata?: Record<string, unknown> | null
  categories?: { name?: string }[] | null
}

/** Поля сведений о товаре, по которым ищем (кроме названия и разделов). */
const ПОЛЯ = ["color", "kind", "gender", "tkan", "fabric", "cut", "style", "model", "article"]

/** Слова, которые ничего не уточняют. */
const ПУСТЫЕ = new Set(["и", "в", "с", "на", "для", "под", "из", "по", "от", "до", "или"])

const ОКОНЧАНИЯ = [
  "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
  "ая", "яя", "ое", "ее", "ые", "ие", "ый", "ий", "ой", "ую", "юю",
  "ых", "их", "ым", "им", "ом", "ем", "ах", "ях", "ов", "ев", "ам", "ям",
  "а", "я", "ы", "и", "у", "ю", "е", "о", "ь",
]

/** Строчные буквы, «ё» как «е», всё лишнее — в пробелы. */
export const привести = (текст: string) =>
  текст
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/g, " ")
    .trim()

/** Основа слова: без окончания, но не короче трёх букв. Числа не трогаем. */
export const основа = (слово: string) => {
  if (/\d/.test(слово) || слово.length < 4) {
    return слово
  }
  for (const о of ОКОНЧАНИЯ) {
    if (слово.endsWith(о) && слово.length - о.length >= 3) {
      return слово.slice(0, -о.length)
    }
  }
  return слово
}

const ЛАТИНИЦА = "qwertyuiop[]asdfghjkl;'zxcvbnm,.`"
const КИРИЛЛИЦА = "йцукенгшщзхъфывапролджэячсмитьбюё"

/** «,h.rb» — это «брюки», набранные в английской раскладке. */
export const изДругойРаскладки = (текст: string) =>
  текст
    .toLowerCase()
    .split("")
    .map((б) => {
      const i = ЛАТИНИЦА.indexOf(б)
      return i >= 0 ? КИРИЛЛИЦА[i] : б
    })
    .join("")

/** Слова запроса, уже основами. Артикул «3149-46/170» даёт «3149». */
export const словаЗапроса = (запрос: string): string[] => {
  // размер и рост в артикуле товар не уточняют: у всех размеров он один
  const безРазмера = запрос.replace(/(\d{3,})-\d+(\/\d+)?/g, "$1")
  return привести(безРазмера)
    .split(" ")
    .filter((с) => с && !ПУСТЫЕ.has(с))
    .map(основа)
}

const словаТовара = (т: ТоварДляПоиска): string[] => {
  const части: string[] = [т.title ?? ""]
  for (const поле of ПОЛЯ) {
    const з = т.metadata?.[поле]
    if (typeof з === "string") {
      части.push(з)
    }
  }
  for (const к of т.categories ?? []) {
    части.push(к.name ?? "")
  }
  return привести(части.join(" ")).split(" ").filter(Boolean)
}

const отобрать = (товары: ТоварДляПоиска[], слова: string[]) =>
  товары
    .filter((т) => {
      const есть = словаТовара(т)
      return слова.every((с) => есть.some((е) => е.startsWith(с)))
    })
    .map((т) => т.id)

/**
 * id товаров, подходящих под запрос. Ничего не нашлось, а в запросе
 * латиница — пробуем прочитать его как набранный не в той раскладке.
 */
export const найтиПоСловам = (товары: ТоварДляПоиска[], запрос: string): string[] => {
  const слова = словаЗапроса(запрос)
  if (!слова.length) {
    return []
  }

  const найдено = отобрать(товары, слова)
  if (найдено.length || !/[a-z,.;'\[\]`]/i.test(запрос)) {
    return найдено
  }

  const иначе = словаЗапроса(изДругойРаскладки(запрос))
  return иначе.length ? отобрать(товары, иначе) : []
}
