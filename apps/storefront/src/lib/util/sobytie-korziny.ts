/**
 * Событие «корзина изменилась» — от кнопки «В корзину» к значку в шапке.
 *
 * Значок рисует сервер, и ответ на добавление иногда приносил его со
 * старым числом: вещь в корзине, а на значке «0» (плавающая гонка, на
 * боевой примерно раз из четырёх в новом сеансе). По этому событию значок
 * сам переспрашивает сервер отдельным запросом.
 */
export const СОБЫТИЕ_КОРЗИНЫ = "volento:korzina"

export const сообщитьОКорзине = () => {
  try {
    window.dispatchEvent(new Event(СОБЫТИЕ_КОРЗИНЫ))
  } catch {
    // без события значок обновится при следующем переходе
  }
}
