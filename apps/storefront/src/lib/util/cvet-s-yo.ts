/**
 * Название цвета (или название товара с цветом в конце) для показа
 * покупателю.
 *
 * В каталоге цвета записаны без «ё»: «черный», «темно-синий». Так они
 * пришли из выгрузки, и отбор с поиском на эту запись опираются, поэтому
 * сами данные не трогаем, а букву возвращаем только при показе.
 */
// Только слова-цвета: «чернильный» и «темнота» остаются как есть.
const КОНЕЦ = "(?=ый|ая|ое|ые|ого|ой|ом|ых|ым|ую|о-)"
// Первая буква слова сохраняется как была: «Черный» станет «Чёрный».
const ЗАМЕНЫ: [RegExp, string][] = [
  [new RegExp(`(^|[^а-яё])(ч)ерн${КОНЕЦ}`, "gi"), "$1$2ёрн"],
  [/(^|[^а-яё])(т)емно(?=-)/gi, "$1$2ёмно"],
  [new RegExp(`(^|[^а-яё])(ж)елт${КОНЕЦ}`, "gi"), "$1$2ёлт"],
  [new RegExp(`(^|[^а-яё])(зел)ен${КОНЕЦ}`, "gi"), "$1$2ён"],
  [new RegExp(`(^|[^а-яё])(т)епл${КОНЕЦ}`, "gi"), "$1$2ёпл"],
]

export const цветСЁ = (цвет: string): string =>
  ЗАМЕНЫ.reduce((с, [что, чем]) => с.replace(что, чем), цвет)
