import type { MetadataRoute } from "next"

import { getBaseURL } from "@lib/util/env"

/**
 * Файл для поисковых роботов.
 *
 * Пока магазин не запущен, индексацию держим закрытой нарочно. Причин
 * две: адрес `slytn.ru` временный, и всё, что поисковики успеют на нём
 * найти, после переезда превратится в битые ссылки; а продавать мы ещё
 * не начали — покупатель, пришедший из поиска, упрётся в магазин без
 * оплаты.
 *
 * Открыть индексацию — одна переменная: ALLOW_INDEXING=true в настройках
 * витрины (имя латиницей: кириллицу в именах переменных окружения
 * командная оболочка не принимает). После этого поисковикам станет видно всё, кроме
 * личного кабинета, корзины и оформления: там нечего показывать, а
 * попадать в выдачу чужим корзинам ни к чему.
 */
const МОЖНО = process.env.ALLOW_INDEXING === "true"

export default function robots(): MetadataRoute.Robots {
  const адрес = getBaseURL()

  if (!МОЖНО) {
    return {
      rules: [{ userAgent: "*", disallow: "/" }],
    }
  }

  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: ["/*/account", "/*/cart", "/*/checkout", "/*/order/"],
      },
    ],
    sitemap: `${адрес}/sitemap.xml`,
    host: адрес,
  }
}
