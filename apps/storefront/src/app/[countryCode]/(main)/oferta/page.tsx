import { Metadata } from "next"
import { notFound } from "next/navigation"

import { getHomeContent } from "@lib/data/home-banner"
import PageLayout, { Раздел } from "@modules/content/components/page-layout"

export const metadata: Metadata = {
  title: "Публичная оферта — Volento",
}

/**
 * Публичная оферта — договор розничной купли-продажи.
 *
 * Как и политика, открывается только при заполненных реквизитах.
 *
 * Текст составлен по общим правилам розничной торговли и закона о защите
 * прав потребителей, но это не заменяет юриста: перед запуском продаж
 * оферту нужно вычитать специалистом под конкретное юрлицо и товар.
 */
export default async function Page(props: {
  params: Promise<{ countryCode: string }>
}) {
  const { countryCode } = await props.params
  const { реквизиты } = await getHomeContent(countryCode)

  if (!реквизиты) {
    notFound()
  }

  const { наименование, инн, огрн, адрес, почта } = реквизиты

  return (
    <PageLayout
      заголовок="Публичная оферта"
      подзаголовок="Договор розничной купли-продажи в интернет-магазине Volento"
    >
      <Раздел название="Продавец">
        <p>
          {наименование}, ИНН {инн}
          {огрн ? `, ОГРН ${огрн}` : ""}, адрес: {адрес}, почта для обращений:{" "}
          {почта}.
        </p>
        <p>
          Настоящий документ — публичная оферта: предложение заключить договор
          розничной купли-продажи на условиях, изложенных ниже. Оформляя заказ,
          вы принимаете эти условия.
        </p>
      </Раздел>

      <Раздел название="Товар">
        <p>
          Товаром считается одежда, описанная в карточках на сайте.
          Характеристики, состав, цена и наличие указаны там же. Цвет на
          фотографии может незначительно отличаться от настоящего из-за настроек
          экрана — это не считается недостатком товара.
        </p>
      </Раздел>

      <Раздел название="Заказ">
        <p>
          Заказ оформляется на сайте. После оформления продавец подтверждает
          наличие. Если товара не окажется, заказ отменяется, а деньги
          возвращаются полностью.
        </p>
        <p>
          Цена — та, что указана на сайте в момент оформления. Стоимость
          доставки считается отдельно и показывается до оплаты.
        </p>
      </Раздел>

      <Раздел название="Оплата">
        <p>
          Оплата производится на сайте банковской картой или через Систему
          быстрых платежей. Обязательства покупателя считаются исполненными
          с момента поступления денег продавцу. Электронный чек направляется на
          указанную покупателем почту.
        </p>
      </Раздел>

      <Раздел название="Доставка">
        <p>
          Доставка выполняется службами доставки по выбору покупателя: до пункта
          выдачи или до адреса. Сроки и стоимость показываются при оформлении.
          Риск случайной гибели товара переходит к покупателю с момента
          вручения.
        </p>
      </Раздел>

      <Раздел название="Возврат">
        <p>
          Покупатель вправе отказаться от товара в любое время до его передачи
          и в течение семи дней после. Если памятка о порядке возврата не была
          передана вместе с товаром, срок составляет три месяца.
        </p>
        <p>
          Возврат возможен, если сохранены товарный вид, потребительские
          свойства и ярлыки. Деньги возвращаются в течение десяти дней с момента
          получения требования, за вычетом расходов на обратную доставку, кроме
          случаев, когда возврат вызван недостатком товара.
        </p>
      </Раздел>

      <Раздел название="Ответственность">
        <p>
          Стороны отвечают по обязательствам в соответствии с законодательством
          Российской Федерации. Продавец не отвечает за задержки, вызванные
          обстоятельствами непреодолимой силы, и за неверные данные, указанные
          покупателем при оформлении.
        </p>
      </Раздел>

      <Раздел название="Персональные данные">
        <p>
          Оформляя заказ, покупатель соглашается на обработку персональных
          данных на условиях политики, опубликованной на сайте.
        </p>
      </Раздел>
    </PageLayout>
  )
}
