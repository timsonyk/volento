import { Metadata } from "next"
import { notFound } from "next/navigation"

import { getHomeContent } from "@lib/data/home-banner"
import PageLayout, {
  Перечень,
  Пункт,
  Раздел,
} from "@modules/content/components/page-layout"

export const metadata: Metadata = {
  title: "Согласие на обработку персональных данных | Volento",
}

/** Дата последней редакции. Менять при любой правке текста. */
const ДАТА_РЕДАКЦИИ = "20 октября 2026 г."

/**
 * Согласие на обработку персональных данных — отдельным документом.
 *
 * С 1 сентября 2025 года согласие нельзя прятать в оферту, соглашение
 * или политику (ч. 1 ст. 9 152-ФЗ в новой редакции): у него свой текст
 * и своя отметка при оформлении заказа и регистрации. Состав — по ч. 4
 * ст. 9: оператор, цели, перечень данных, действия, способы, кому
 * передаём, срок и порядок отзыва.
 *
 * Как и остальные юридические страницы, открывается только при
 * заполненных реквизитах продавца (админка, «Главная», поля юр_*).
 */
export default async function Page(props: {
  params: Promise<{ countryCode: string }>
}) {
  const { countryCode } = await props.params
  const { реквизиты } = await getHomeContent(countryCode)

  if (!реквизиты) {
    notFound()
  }

  const { наименование, инн, огрн, адрес, почта } = реквизиты

  return (
    <PageLayout
      заголовок="Согласие на обработку персональных данных"
      подзаголовок={`Редакция от ${ДАТА_РЕДАКЦИИ}`}
    >
      <Раздел название="1. Кто даёт согласие и кому">
        <Пункт номер="1.1.">
          Отмечая согласие при оформлении заказа или регистрации на сайте
          Volento, я, действуя свободно, своей волей и в своём интересе,
          даю согласие оператору — {наименование}, ИНН {инн}
          {огрн ? `, ОГРНИП ${огрн}` : ""}, адрес: {адрес} (далее —
          Оператор) — на обработку моих персональных данных на условиях
          ниже.
        </Пункт>
      </Раздел>

      <Раздел название="2. Цели обработки">
        <Перечень>
          <li>оформление, оплата, сборка и доставка заказа;</li>
          <li>выдача кассового чека;</li>
          <li>обработка возвратов и обменов;</li>
          <li>
            уведомления о заказе и ответы на мои обращения;
          </li>
          <li>ведение личного кабинета, если я регистрируюсь.</li>
        </Перечень>
      </Раздел>

      <Раздел название="3. Какие данные">
        <Перечень>
          <li>фамилия и имя;</li>
          <li>номер телефона;</li>
          <li>адрес электронной почты;</li>
          <li>адрес доставки (пункт выдачи);</li>
          <li>сведения о заказах;</li>
          <li>комментарий к заказу, если я его оставил.</li>
        </Перечень>
      </Раздел>

      <Раздел название="4. Что Оператор может делать с данными">
        <Пункт номер="4.1.">
          Сбор, запись, систематизация, накопление, хранение, уточнение
          (обновление, изменение), извлечение, использование, передача
          (предоставление, доступ), блокирование, удаление, уничтожение.
        </Пункт>
        <Пункт номер="4.2.">
          Обработка смешанная: с использованием средств автоматизации
          и без них, с передачей по сети интернет.
        </Пункт>
      </Раздел>

      <Раздел название="5. Кому передаются данные">
        <Пункт номер="5.1.">
          Только в объёме, нужном для целей из раздела 2:
        </Пункт>
        <Перечень>
          <li>
            сервису ApiShip и службам доставки (Яндекс Доставка, СДЭК) —
            имя, фамилия, телефон и адрес доставки;
          </li>
          <li>
            банку, принимающему оплату, — сведения для расчётов и возвратов;
          </li>
          <li>
            сервису облачной кассы АТОЛ Онлайн и оператору фискальных
            данных — электронная почта или телефон для чека;
          </li>
          <li>
            хостинг-провайдеру Рег.ру — хранение данных на серверах
            в России.
          </li>
        </Перечень>
        <Пункт номер="5.2.">
          Данные хранятся и обрабатываются на территории Российской
          Федерации и за её пределы не передаются.
        </Пункт>
      </Раздел>

      <Раздел название="6. Срок и отзыв согласия">
        <Пункт номер="6.1.">
          Согласие действует до достижения целей обработки или до его
          отзыва.
        </Пункт>
        <Пункт номер="6.2.">
          Я могу отозвать согласие в любой момент, написав Оператору на{" "}
          {почта}. После отзыва Оператор прекращает обработку и удаляет
          данные в срок, установленный законом, кроме тех, которые обязан
          хранить по закону (сведения о покупках и кассовых чеках).
        </Пункт>
      </Раздел>
    </PageLayout>
  )
}
