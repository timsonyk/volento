import { Metadata } from "next"
import { notFound } from "next/navigation"

import { getHomeContent } from "@lib/data/home-banner"
import PageLayout, { Раздел } from "@modules/content/components/page-layout"

export const metadata: Metadata = {
  title: "Политика обработки персональных данных — Volento",
}

/**
 * Политика обработки персональных данных.
 *
 * Страница открывается, только когда в админке заполнены реквизиты
 * продавца: политика без наименования, ИНН и адреса оператора юридической
 * силы не имеет, а публиковать пустой бланк — вводить покупателя
 * в заблуждение.
 */
export default async function Page(props: {
  params: Promise<{ countryCode: string }>
}) {
  const { countryCode } = await props.params
  const { реквизиты } = await getHomeContent(countryCode)

  if (!реквизиты) {
    notFound()
  }

  const { наименование, инн, огрн, адрес, почта } = реквизиты

  return (
    <PageLayout
      заголовок="Политика обработки персональных данных"
      подзаголовок={`Оператор: ${наименование}`}
    >
      <Раздел название="Кто обрабатывает данные">
        <p>
          {наименование}, ИНН {инн}
          {огрн ? `, ОГРН ${огрн}` : ""}, адрес: {адрес}. Связаться по вопросам
          обработки данных: {почта}.
        </p>
        <p>
          Политика составлена в соответствии с Федеральным законом от 27.07.2006
          № 152-ФЗ «О персональных данных» и определяет порядок обработки
          персональных данных посетителей и покупателей сайта.
        </p>
      </Раздел>

      <Раздел название="Какие данные мы собираем">
        <p>
          Имя и фамилию, адрес электронной почты, номер телефона, адрес
          доставки — всё это вы сообщаете сами при оформлении заказа или
          регистрации. Без них заказ невозможно собрать и доставить.
        </p>
        <p>
          Дополнительно сохраняются данные о заказах: состав, суммы, статусы,
          и технические сведения — адрес устройства в сети, страницы, которые вы
          открывали. Технические сведения нужны, чтобы сайт работал и чтобы мы
          видели сбои.
        </p>
      </Раздел>

      <Раздел название="Зачем">
        <p>
          Чтобы принять и выполнить заказ, доставить его, выдать чек, ответить
          на обращение и выполнить требования закона о хранении документов.
          Присылать рекламу мы можем только с вашего отдельного согласия,
          и от неё можно отписаться в любой момент.
        </p>
      </Раздел>

      <Раздел название="Кому передаём">
        <p>
          Службам доставки — имя, телефон и адрес получателя, иначе посылку
          некому вручить. Банку-эквайеру — сумму и данные заказа для проведения
          платежа. Оператору фискальных данных — состав заказа для чека.
          Больше никому: мы не продаём и не передаём данные для рекламы.
        </p>
      </Раздел>

      <Раздел название="Сколько храним">
        <p>
          Пока действует ваш аккаунт и пока этого требует закон для документов
          о сделках. После истечения срока данные удаляются или обезличиваются.
        </p>
      </Раздел>

      <Раздел название="Ваши права">
        <p>
          Вы можете узнать, какие данные о вас у нас есть, исправить их,
          потребовать удаления или отозвать согласие на обработку. Напишите на{" "}
          {почта} — ответим в срок, установленный законом.
        </p>
        <p>
          Отзыв согласия не мешает нам хранить документы, которые мы обязаны
          хранить по закону, — например, сведения о совершённых покупках.
        </p>
      </Раздел>

      <Раздел название="Как защищаем">
        <p>
          Соединение с сайтом шифруется. Доступ к данным есть только у тех, кому
          он нужен для работы. Пароли хранятся в необратимо преобразованном
          виде — восстановить их нельзя даже нам.
        </p>
      </Раздел>

      <Раздел название="Файлы cookie">
        <p>
          Сайт сохраняет в браузере небольшие файлы, чтобы помнить содержимое
          корзины и то, что вы вошли в аккаунт. Их можно отключить в настройках
          браузера, но тогда корзина перестанет работать.
        </p>
      </Раздел>
    </PageLayout>
  )
}
