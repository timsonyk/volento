"use client"

import { useEffect, useState } from "react"

/**
 * Будильник для страницы.
 *
 * После действия покупателя (сменил количество, сохранил телефон, выбрал
 * доставку) витрина получает с сервера свежую страницу кусками. Если
 * последний кусок приходит в неудачный миг, React теряет сигнал «данные
 * готовы» и продолжает показывать старое, пока его не разбудит любое
 * другое обновление. Так в корзине примерно каждая седьмая смена
 * количества ждала три секунды вместо половины, а в кабинете после
 * сохранения оставался прежний телефон.
 *
 * Здесь мы следим за такими ответами и, когда ответ дочитан до конца,
 * делаем пустое обновление этого крошечного компонента. React при любом
 * обновлении заново проверяет отложенное и дорисовывает страницу.
 *
 * Следим только за запросами самой витрины за свежей страницей (заголовки
 * rsc и next-action). Предзагрузку ссылок не трогаем.
 */
const ТОЛЧКИ = [30, 200, 600]

export default function Budilnik() {
  const [, толкнуть] = useState(0)

  useEffect(() => {
    const прежний = window.fetch
    let жив = true
    const таймеры = new Set<number>()

    const разбудить = () => {
      for (const мс of ТОЛЧКИ) {
        const т = window.setTimeout(() => {
          таймеры.delete(т)
          if (жив) толкнуть((н) => н + 1)
        }, мс)
        таймеры.add(т)
      }
    }

    const дочитать = async (ответ: Response) => {
      try {
        const поток = ответ.body?.getReader()
        if (поток) {
          while (!(await поток.read()).done) {
            // читаем копию до конца, само содержимое не нужно
          }
        }
      } catch {
        // оборванный ответ тоже повод перепроверить страницу
      }
      разбудить()
    }

    const нужен = (вход: RequestInfo | URL, настройки?: RequestInit) => {
      try {
        const заголовки = new Headers(
          настройки?.headers ??
            (вход instanceof Request ? вход.headers : undefined)
        )
        if (заголовки.has("next-router-prefetch")) return false
        return заголовки.has("rsc") || заголовки.has("next-action")
      } catch {
        return false
      }
    }

    const свой: typeof window.fetch = async (вход, настройки) => {
      const ответ = await прежний(вход, настройки)
      if (жив && нужен(вход, настройки)) {
        try {
          void дочитать(ответ.clone())
        } catch {
          разбудить()
        }
      }
      return ответ
    }
    window.fetch = свой

    return () => {
      жив = false
      таймеры.forEach((т) => window.clearTimeout(т))
      // возвращаем прежний fetch, только если поверх нас никто не встал
      if (window.fetch === свой) window.fetch = прежний
    }
  }, [])

  return null
}
