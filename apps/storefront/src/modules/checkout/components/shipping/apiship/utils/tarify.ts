import { convertToLocale } from "@lib/util/money"

import { ApishipTariff } from "../types"

/**
 * Приведение тарифов служб доставки к тому, что можно показать человеку.
 *
 * Служба отдаёт названия вида «Посылка склад-склад», «Экспресс
 * постамат-склад», «Супер-экспресс до 16 склад-постамат». Хвост из двух
 * слов — это откуда забирают и куда везут, на языке склада. Покупателю он
 * ничего не говорит: он уже выбрал пункт на карте, и куда везут — видно.
 *
 * Первое слово важно нам: мы сдаём посылку в пункт выдачи, поэтому
 * тарифы, которые начинаются с постамата или с двери (курьер приезжает к
 * нам), не подходят — сдать по ним посылку мы не сможем.
 */

/** Откуда забирают и куда везут: хвост названия тарифа. */
const ПЛЕЧИ = /\s+(склад|постамат|дверь)\s*[-–—]\s*(склад|постамат|дверь)\s*$/i

/** Мы отдаём посылку сами, в пункте выдачи. */
const НАШЕ_ПЛЕЧО = "склад"

/** Название без складского хвоста: «Посылка склад-склад» → «Посылка». */
export const имяТарифа = (tariff: ApishipTariff) => {
  const имя = (tariff.tariffName ?? "").trim()
  return имя.replace(ПЛЕЧИ, "").trim() || имя || "Доставка"
}

/**
 * Можно ли сдать посылку по этому тарифу в пункте выдачи.
 *
 * Если в названии плечи не указаны, верим полю pickupTypes: 2 — это
 * сдача на складе, то есть в пункте выдачи.
 */
export const отПВЗ = (tariff: ApishipTariff) => {
  const плечи = (tariff.tariffName ?? "").match(ПЛЕЧИ)
  if (плечи) {
    return плечи[1].toLowerCase() === НАШЕ_ПЛЕЧО
  }
  const типы = (tariff as { pickupTypes?: number[] }).pickupTypes
  return !Array.isArray(типы) || типы.includes(2)
}

const цифра = (v: unknown) => (typeof v === "number" ? v : Number.POSITIVE_INFINITY)

/** Цена тарифа: без скидки, если она есть, иначе обычная. */
export const ценаТарифа = (tariff: ApishipTariff) =>
  typeof tariff.deliveryCostOriginal === "number"
    ? tariff.deliveryCostOriginal
    : tariff.deliveryCost

/**
 * Тарифы, годные к показу: только те, что мы можем сдать в пункте, без
 * повторов и по возрастанию цены.
 *
 * Повторы возникают сами собой: «Экспресс склад-склад» и «Экспресс
 * склад-постамат» после чистки названия становятся одним «Экспрессом» с
 * одной ценой. Оставляем тот, что дешевле, а при равной цене — быстрее.
 *
 * Если отбор не оставил ничего (бывает у одиночных пунктов), показываем
 * что есть: пустой список выглядел бы поломкой.
 */
export const годныеТарифы = (tariffs: ApishipTariff[]) => {
  const свои = tariffs.filter(отПВЗ)
  const исходные = свои.length ? свои : tariffs

  const лучшие = new Map<string, ApishipTariff>()
  for (const t of исходные) {
    const ключ = `${t.providerKey}|${имяТарифа(t)}`
    const было = лучшие.get(ключ)
    if (!было) {
      лучшие.set(ключ, t)
      continue
    }
    const дешевле = цифра(ценаТарифа(t)) < цифра(ценаТарифа(было))
    const такЖе = цифра(ценаТарифа(t)) === цифра(ценаТарифа(было))
    const быстрее = цифра(t.daysMax) < цифра(было.daysMax)
    if (дешевле || (такЖе && быстрее)) {
      лучшие.set(ключ, t)
    }
  }

  return [...лучшие.values()].sort(
    (a, b) =>
      цифра(ценаТарифа(a)) - цифра(ценаТарифа(b)) ||
      цифра(a.daysMax) - цифра(b.daysMax)
  )
}

const ДЕНЬ = ["дней", "день", "дня", "дня", "дня"]

const дней = (n: number) => {
  const две = n % 100
  if (две >= 11 && две <= 14) return "дней"
  return ДЕНЬ[n % 10] ?? "дней"
}

/** «2 дня», «1–2 дня» — или ничего, если служба срок не назвала. */
export const срокТарифа = (tariff: ApishipTariff) => {
  const min = tariff.daysMin ?? 0
  const max = tariff.daysMax ?? 0
  if (!min && !max) {
    return null
  }
  if (!min || min === max) {
    const n = max || min
    return `${n} ${дней(n)}`
  }
  return `${min}–${max} ${дней(max)}`
}

/** Цена рублями, как в остальном магазине. */
export const ценаСтрокой = (
  сумма: number | undefined,
  валюта = "rub"
) =>
  typeof сумма === "number"
    ? convertToLocale({ amount: сумма, currency_code: валюта })
    : "—"
