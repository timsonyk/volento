/**
 * Адрес пункта выдачи для списка.
 *
 * Служба доставки присылает «420000, Республика Татарстан, Казань,
 * проспект Ильгама Шакирова, 24». Город покупатель только что выбрал сам,
 * индекс и область ему в списке ни к чему: улицу приходилось искать глазами
 * в середине строки, а список шёл по индексам, а не по улицам.
 *
 * Отрезаем всё до города включительно, если город стоит среди первых
 * четырёх частей. Не нашли город — убираем только индекс. Сам адрес в
 * карточке пункта и в заказе остаётся полным.
 */
const просто = (с: string) =>
  с
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/^(г\.?|город)\s+/, "")
    .trim()

export function короткийАдрес(адрес?: string | null, город?: string | null): string {
  const полный = (адрес ?? "").trim()
  if (!полный) return ""
  const части = полный.split(",").map((ч) => ч.trim()).filter(Boolean)

  const нужный = просто(город ?? "")
  if (нужный) {
    const где = части.slice(0, 4).findIndex((ч) => просто(ч) === нужный)
    if (где >= 0 && где < части.length - 1) {
      return части.slice(где + 1).join(", ")
    }
  }

  if (/^\d{6}$/.test(части[0] ?? "") && части.length > 1) {
    return части.slice(1).join(", ")
  }
  return полный
}

/**
 * Название пункта для покупателя.
 *
 * СДЭК присылает вместо названия свой код и тот же адрес: «MSK2181,
 * Москва, 1-й Ботанический пр-д». Покупателю код ничего не говорит, а
 * адрес уже стоит строкой выше. Такое название не показываем вовсе.
 */
export function имяПункта(имя?: string | null): string {
  const чистое = (имя ?? "").trim()
  if (/^[A-Z]{2,6}\d+\b/.test(чистое)) return ""
  return чистое
}
