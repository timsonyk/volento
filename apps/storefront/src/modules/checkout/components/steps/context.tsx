"use client"

import { createContext, useContext } from "react"

/**
 * Через этот контекст блок оформления говорит, заполнен он или нет.
 *
 * Почему не считать всё по корзине: корзина приезжает с сервера, и пока
 * она не обновилась, шаг оставался бы закрытым — человек заполнил поля,
 * а следующий пункт ещё серый. Блок знает о себе раньше сервера, поэтому
 * сообщает о готовности сам, а корзина остаётся запасным источником.
 */
export type КлючШага = "город" | "доставка" | "получатель" | "оплата"

type Значение = {
  отметить: (ключ: КлючШага, готов: boolean) => void
}

const Контекст = createContext<Значение>({ отметить: () => {} })

export const ПровайдерШагов = Контекст.Provider

export const useОтметка = () => useContext(Контекст).отметить
