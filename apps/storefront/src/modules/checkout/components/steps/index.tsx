"use client"

import { useMemo, useState } from "react"

import { HttpTypes } from "@medusajs/types"

import Шаг from "../step"
import { КлючШага, ПровайдерШагов } from "./context"

/**
 * Порядок оформления заказа.
 *
 * Сами блоки приходят готовыми с сервера и передаются сюда как есть —
 * здесь только решается, какой из них уже можно трогать. Открыт тот
 * пункт, у которого заполнены все предыдущие.
 *
 * Готовность берём из двух мест: что блок сказал о себе сам (быстро, до
 * обращения к серверу) и что видно по корзине (надёжно, переживает
 * перезагрузку страницы). Слово блока главнее — он знает о себе раньше.
 */
const Шаги = ({
  cart,
  город,
  доставка,
  получатель,
  оплата,
  проверка,
}: {
  cart: HttpTypes.StoreCart
  город: React.ReactNode
  доставка: React.ReactNode
  получатель: React.ReactNode
  оплата: React.ReactNode
  проверка: React.ReactNode
}) => {
  const [свои, setСвои] = useState<Partial<Record<КлючШага, boolean>>>({})

  const [способОплаты, выбратьСпособ] = useState(
    cart.payment_collection?.payment_sessions?.[0]?.provider_id ?? ""
  )

  const значение = useMemo(
    () => ({
      отметить: (ключ: КлючШага, готов: boolean) =>
        setСвои((было) =>
          было[ключ] === готов ? было : { ...было, [ключ]: готов }
        ),
      способОплаты,
      выбратьСпособ,
    }),
    [способОплаты]
  )

  const адрес = cart.shipping_address

  const поКорзине: Record<КлючШага, boolean> = {
    город: !!адрес?.city?.trim(),
    доставка: (cart.shipping_methods?.length ?? 0) > 0,
    получатель: !!(
      cart.email &&
      адрес?.first_name?.trim() &&
      адрес?.last_name?.trim() &&
      адрес?.phone?.trim()
    ),
    оплата: (cart.payment_collection?.payment_sessions?.length ?? 0) > 0,
  }

  const готов = (ключ: КлючШага) => свои[ключ] ?? поКорзине[ключ]

  return (
    <ПровайдерШагов value={значение}>
      {/* Пункты разделены тонкой линией сверху — её рисует сам «Шаг».
          Отступы между ними держим одинаковыми, чтобы линии шли
          ровным шагом. */}
      <div className="w-full">
        <Шаг
          номер={1}
          заголовок="Куда везём"
          подпись="Начните вводить название города — подскажем. От города зависят сроки и цена доставки."
          открыт
          первый
          готов={готов("город")}
          почему=""
        >
          {город}
        </Шаг>

        <Шаг
          номер={2}
          заголовок="Доставка"
          подпись="Выберите службу и пункт выдачи — цену и срок посчитаем сразу."
          открыт={готов("город")}
          готов={готов("доставка")}
          почему="Сначала выберите город"
        >
          {доставка}
        </Шаг>

        <Шаг
          номер={3}
          заголовок="Получатель"
          подпись="На почту придёт подтверждение заказа, по телефону позвонит курьер."
          открыт={готов("доставка")}
          готов={готов("получатель")}
          почему="Сначала выберите способ доставки"
        >
          {получатель}
        </Шаг>

        <Шаг
          номер={4}
          заголовок="Оплата"
          открыт={готов("получатель")}
          готов={готов("оплата")}
          почему="Сначала заполните данные получателя"
        >
          {оплата}
        </Шаг>

        <Шаг
          номер={5}
          заголовок="Проверка заказа"
          открыт={готов("оплата")}
          готов={false}
          почему="Сначала выберите способ оплаты"
        >
          {проверка}
        </Шаг>
      </div>
    </ПровайдерШагов>
  )
}

export default Шаги
