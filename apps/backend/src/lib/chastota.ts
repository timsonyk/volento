/**
 * Сторож частоты для писем с кодом входа.
 *
 * У самого кода защита уже есть: письмо на один адрес не чаще раза в
 * минуту. Но адресов можно перебирать сколько угодно, и тогда наш сайт
 * начнёт рассылать письма незнакомым людям. Почтовые службы за такое
 * отправляют в спам весь домен, и коды перестанут доходить покупателям.
 *
 * Поэтому считаем ещё и по тому, кто просит: с одного адреса в сети не
 * больше ЛИМИТ_С_АДРЕСА писем за ОКНО, а всего не больше ЛИМИТ_ВСЕГО.
 *
 * Счёт лежит в памяти процесса: сервер один, после перезапуска счёт
 * начинается заново, для сторожа этого достаточно.
 */

export const ОКНО = 10 * 60 * 1000
export const ЛИМИТ_С_АДРЕСА = 8
export const ЛИМИТ_ВСЕГО = 200

export class Сторож {
  private поАдресам = new Map<string, number[]>()
  private все: number[] = []

  private окно: number
  private сАдреса: number
  private всего: number

  constructor(окно = ОКНО, сАдреса = ЛИМИТ_С_АДРЕСА, всего = ЛИМИТ_ВСЕГО) {
    this.окно = окно
    this.сАдреса = сАдреса
    this.всего = всего
  }

  /**
   * Можно ли отправить ещё одно письмо. Возвращает 0, если можно (и
   * засчитывает его), иначе через сколько секунд попробовать снова.
   * Пустой адрес (обращение изнутри сервера) считаем только в общий счёт.
   */
  пропустить(адрес: string, сейчас = Date.now()): number {
    const свежие = (метки: number[]) => метки.filter((т) => сейчас - т < this.окно)
    const ждать = (метки: number[]) => Math.max(1, Math.ceil((метки[0] + this.окно - сейчас) / 1000))

    this.все = свежие(this.все)
    if (this.все.length >= this.всего) {
      return ждать(this.все)
    }

    if (адрес) {
      const его = свежие(this.поАдресам.get(адрес) ?? [])
      if (его.length >= this.сАдреса) {
        this.поАдресам.set(адрес, его)
        return ждать(его)
      }
      его.push(сейчас)
      this.поАдресам.set(адрес, его)
    }

    this.все.push(сейчас)

    // не копим адреса, которые давно не приходили
    if (this.поАдресам.size > 5000) {
      for (const [а, метки] of this.поАдресам) {
        if (!свежие(метки).length) {
          this.поАдресам.delete(а)
        }
      }
    }
    return 0
  }
}

/**
 * Адрес того, кто просит код.
 *
 * Запрос пришёл через nginx: берём последний адрес из X-Forwarded-For,
 * его дописал сам nginx, подделать его нельзя. Запрос без этого
 * заголовка пришёл изнутри сервера, от витрины: она передаёт адрес
 * покупателя в своём заголовке.
 */
export const ЗАГОЛОВОК_ПОКУПАТЕЛЯ = "x-pokupatel-ip"

export const ктоПросит = (заголовки: Record<string, unknown>): string => {
  const последний = (значение: unknown) =>
    String(значение ?? "")
      .split(",")
      .pop()!
      .trim()
      .replace(/^::ffff:/, "")
  return последний(заголовки["x-forwarded-for"]) || последний(заголовки[ЗАГОЛОВОК_ПОКУПАТЕЛЯ])
}
