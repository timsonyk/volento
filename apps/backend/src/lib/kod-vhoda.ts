import crypto from "crypto"

/**
 * Общая часть входа по коду: её знают и ручка, которая код выдаёт, и
 * провайдер, который его проверяет.
 *
 * Пароля у покупателя нет вовсе. Вместо него — шестизначное число,
 * живущее десять минут: человек получает его письмом и вводит на сайте.
 * Шесть цифр, а не четыре: угадать одну из миллиона за пять попыток
 * практически невозможно, а из десяти тысяч — уже ощутимо.
 */

/** Сколько цифр в коде. */
export const ДЛИНА_КОДА = 6

/** Сколько живёт код, миллисекунды. */
export const ЖИВЁТ = 10 * 60 * 1000

/** Сколько раз можно ошибиться, прежде чем код сгорит. */
export const ПОПЫТОК = 5

/** Не чаще одного письма в минуту на адрес. */
export const ПАУЗА_МЕЖДУ_ПИСЬМАМИ = 60 * 1000

/** Имя провайдера: оно же в адресе /auth/customer/kod. */
export const ПРОВАЙДЕР = "kod"

/**
 * Случайный код. Берём из криптографического источника, а не из
 * Math.random: тот предсказуем, и по нескольким кодам подряд можно
 * вычислить следующие.
 */
export const новыйКод = (): string => {
  const предел = 10 ** ДЛИНА_КОДА
  // отбрасываем хвост диапазона, иначе младшие числа выпадали бы чаще
  const потолок = Math.floor(0xffffffff / предел) * предел
  let n: number
  do {
    n = crypto.randomBytes(4).readUInt32BE(0)
  } while (n >= потолок)
  return String(n % предел).padStart(ДЛИНА_КОДА, "0")
}

/**
 * Отпечаток кода — его и храним, сам код нигде не лежит.
 *
 * Адрес почты подмешан в отпечаток: без него одинаковые коды у разных
 * людей давали бы одинаковый отпечаток, и по базе было бы видно, у кого
 * сейчас такой же код.
 */
export const отпечаток = (код: string, почта: string): string =>
  crypto
    .createHash("sha256")
    .update(`${код}|${почта.trim().toLowerCase()}`)
    .digest("hex")

/** Сравнение без утечки времени: обычное === выдаёт длину совпадения. */
export const совпадает = (а: string, б: string): boolean => {
  const x = Buffer.from(а)
  const y = Buffer.from(б)
  return x.length === y.length && crypto.timingSafeEqual(x, y)
}

/** Приводим адрес к одному виду: почта нечувствительна к регистру. */
export const почтаКлючом = (почта: string): string => почта.trim().toLowerCase()

/** Что лежит у личности между запросом кода и его вводом. */
export type ЗаписьКода = {
  отпечаток?: string
  годендо?: number
  попыток?: number
  отправленов?: number
}
