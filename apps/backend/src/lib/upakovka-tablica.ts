/**
 * Таблица упаковки — единственное место, где записано, какого размера
 * и веса посылка. ЗАМЕРОВ ОТ СКЛАДА ПОКА НЕТ, числа временные: придут
 * замеры Максима — правим только этот файл.
 *
 * Размеры в сантиметрах, вес в граммах.
 *
 * Пока строк в «pakety» нет, место считается как раньше: пары лежат
 * стопкой, размеры и вес каждой пары — из карточки товара (данные Ozon,
 * обычно 33–40 × 30 × 3–4 см и 400–500 г), а если в карточке пусто — из
 * «para». Цена доставки на сайте считается из тех же карточек, поэтому
 * заявленные размеры и цена сейчас сходятся.
 *
 * Когда появятся замеры — вписываем строки в «pakety», например
 *   { do_par: 2, dlina: 40, shirina: 30, vysota: 8, ves_tary: 30 },
 * do_par — «до стольких пар включительно». Берётся первая строка, куда
 * помещаются все пары пакета; её размеры идут в службу вместо стопки, а
 * вес тары прибавляется к весу пар. Пар больше, чем в последней строке, —
 * снова стопкой.
 */
export type СтрокаУпаковки = {
  do_par: number
  dlina: number
  shirina: number
  vysota: number
  ves_tary: number
}

export const УПАКОВКА = {
  // одна пара в зип-пакете; берётся, когда у товара своих размеров нет
  para: { dlina: 40, shirina: 30, tolshina: 4, ves: 450 },
  pakety: [] as СтрокаУпаковки[],
  // на сколько пакетов склад может разделить один заказ
  maksimum_paketov: 5,
}

export type РазмерыМеста = { length: number; width: number; height: number; weight: number }

type Товар = { quantity?: number; weight?: number; length?: number; width?: number; height?: number }

const число = (з: unknown, запасное: number) => {
  const ч = Number(з)
  return Number.isFinite(ч) && ч > 0 ? ч : запасное
}

/**
 * Размеры и вес одного места по тому, что в нём лежит. Товары — строки
 * посылки, как их собирает плагин ApiShip (вес и размеры штуки, число
 * штук).
 */
export function размерыМеста(товары: Товар[], таблица = УПАКОВКА): РазмерыМеста {
  let пар = 0
  let вес = 0
  let стопка = 0
  let длина = 0
  let ширина = 0

  for (const т of товары) {
    const штук = Math.max(1, Math.trunc(число(т.quantity, 1)))
    const стороны = [
      число(т.height, таблица.para.tolshina),
      число(т.length, таблица.para.shirina),
      число(т.width, таблица.para.dlina),
    ].sort((а, б) => а - б)

    пар += штук
    вес += число(т.weight, таблица.para.ves) * штук
    стопка += стороны[0] * штук
    ширина = Math.max(ширина, стороны[1])
    длина = Math.max(длина, стороны[2])
  }

  const строка = [...таблица.pakety]
    .sort((а, б) => а.do_par - б.do_par)
    .find((с) => пар <= с.do_par)

  if (строка) {
    return {
      length: строка.shirina,
      width: строка.dlina,
      height: строка.vysota,
      weight: вес + строка.ves_tary,
    }
  }

  // как считал плагин: длина места — средняя сторона, ширина — большая
  return { length: ширина, width: длина, height: стопка, weight: вес }
}
