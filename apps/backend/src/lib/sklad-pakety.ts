import { безНомера } from "./primerka"
import { УПАКОВКА, размерыМеста } from "./upakovka-tablica"

/**
 * Один заказ — несколько пакетов (мест).
 *
 * У склада два помещения, и вещи одного заказа могут лежать в разных.
 * Тогда склад делит заказ на пакеты: что собрано в одном помещении —
 * один пакет, в другом — второй. В службу уходит одно отправление из
 * нескольких мест: одна цена, один трек, покупатель получает всё разом
 * в одном пункте. На каждое место служба даёт свою наклейку.
 *
 * Здесь то, что не зависит от Medusa: разбор «pakety» из запроса склада
 * и раскладка посылки по местам для ApiShip. Размеры мест —
 * lib/upakovka-tablica.ts.
 */

// metadata заказа: Пакет[] — как склад разделил последнюю сборку
export const ПАКЕТЫ = "sklad_pakety"
// metadata сборки: { [номер пакета]: когда упакован }
export const УПАКОВАНЫ = "pakety_upakovany"

export type СтрокаПакета = { id: string; quantity: number; kody: string[] }
export type Пакет = { nomer: number; sklad: string | null; stroki: СтрокаПакета[] }

type СтрокаЗаказа = { id: string; quantity: number; variant_sku?: string }

type ПозицияЗапроса = {
  id_stroki?: string
  artikul?: string
  kolichestvo?: number
  kody?: unknown
}

export type Разбор =
  | { ошибка: string; подробности?: Record<string, unknown> }
  | { пакеты: Пакет[]; строки: СтрокаПакета[] }

const МЕТКА_СКЛАДА = 40

/**
 * Запрос склада «собрано» на наш язык. Понимаем оба вида:
 *   { pozicii: [...] }                          — всё одним пакетом;
 *   { pakety: [{ sklad, pozicii: [...] }, …] }  — по пакетам.
 * Одна строка заказа может лежать в двух пакетах (две одинаковые пары
 * из разных помещений) — тогда в каждом своя часть и свои коды.
 *
 * строки в ответе — то же самое, сложенное по строкам заказа: так его
 * ждёт остальная сборка.
 */
export function разобратьСборку(тело: any, заказ: { items: СтрокаЗаказа[] }): Разбор {
  const поПакетам = Array.isArray(тело?.pakety)
  const сырые: { sklad?: unknown; pozicii?: ПозицияЗапроса[] }[] = поПакетам
    ? тело.pakety
    : [{ pozicii: тело?.pozicii }]

  if (поПакетам && тело?.pozicii !== undefined) {
    return { ошибка: "Пришлите либо pozicii, либо pakety — не оба сразу" }
  }
  if (поПакетам && !сырые.length) {
    return { ошибка: "В pakety пусто — пришлите хотя бы один пакет" }
  }
  if (сырые.length > УПАКОВКА.maksimum_paketov) {
    return { ошибка: `Пакетов не больше ${УПАКОВКА.maksimum_paketov}` }
  }

  const пакеты: Пакет[] = []

  for (const [и, сырой] of сырые.entries()) {
    const позиции = сырой?.pozicii

    if (!Array.isArray(позиции) || !позиции.length) {
      return {
        ошибка: поПакетам
          ? `Пакет ${и + 1}: пришлите pozicii — что в нём лежит и коды маркировки по каждой штуке`
          : "Пришлите pozicii: что собрано и коды маркировки по каждой штуке",
      }
    }

    const строки: СтрокаПакета[] = []

    for (const п of позиции) {
      const строка = заказ.items.find((т) =>
        п?.id_stroki ? т.id === String(п.id_stroki) : т.variant_sku === п?.artikul
      )

      if (!строка) {
        return { ошибка: "Такой строки нет в этом заказе", подробности: { poziciya: п } }
      }
      if (строки.some((с) => с.id === строка.id)) {
        return {
          ошибка: "Строка прислана дважды — пришлите её один раз со всеми кодами",
          подробности: { id_stroki: строка.id },
        }
      }

      const сколько = Number(п.kolichestvo)

      if (!Number.isInteger(сколько) || сколько < 0 || сколько > строка.quantity) {
        return {
          ошибка: `Количество от 0 до ${строка.quantity}`,
          подробности: { id_stroki: строка.id },
        }
      }

      const коды = Array.isArray(п.kody) ? п.kody.map((к) => String(к).trim()) : []
      строки.push({ id: строка.id, quantity: сколько, kody: коды })
    }

    const метка = String(сырой?.sklad ?? "").trim().slice(0, МЕТКА_СКЛАДА)
    пакеты.push({ nomer: и + 1, sklad: метка || null, stroki: строки })
  }

  // по строкам заказа: одна строка могла разойтись по пакетам
  const строки: СтрокаПакета[] = []
  for (const п of пакеты) {
    for (const с of п.stroki) {
      const уже = строки.find((х) => х.id === с.id)
      if (уже) {
        уже.quantity += с.quantity
        уже.kody.push(...с.kody)
      } else {
        строки.push({ id: с.id, quantity: с.quantity, kody: [...с.kody] })
      }
    }
  }

  for (const с of строки) {
    const всего = заказ.items.find((т) => т.id === с.id)?.quantity ?? 0
    if (с.quantity > всего) {
      return {
        ошибка: `По пакетам разложено ${с.quantity} шт., а в заказе ${всего}`,
        подробности: { id_stroki: с.id },
      }
    }
  }

  if (поПакетам) {
    const пустой = пакеты.find((п) => !п.stroki.some((с) => с.quantity > 0))
    if (пустой && пакеты.length > 1) {
      return { ошибка: `Пакет ${пустой.nomer} пустой — не присылайте его` }
    }
  }

  return { пакеты, строки }
}

/** Пустые строки долой: в пакете только то, что в нём правда лежит. */
export const безПустых = (пакеты: Пакет[]): Пакет[] =>
  пакеты
    .map((п) => ({ ...п, stroki: п.stroki.filter((с) => с.quantity > 0) }))
    .filter((п) => п.stroki.length)
    .map((п, и) => ({ ...п, nomer: и + 1 }))

/**
 * Пакеты годятся для этой сборки, только если в них ровно то, что в
 * сборке: после неполной сборки или правки в админке состав мог
 * разойтись — тогда отправляем одним местом, это всегда верно.
 */
export function пакетыСборки(пакеты: unknown, собрано: Map<string, number>): Пакет[] {
  if (!Array.isArray(пакеты) || пакеты.length < 2) {
    return []
  }

  const поПакетам = new Map<string, number>()
  for (const п of пакеты as Пакет[]) {
    for (const с of п?.stroki ?? []) {
      поПакетам.set(с.id, (поПакетам.get(с.id) ?? 0) + Number(с.quantity ?? 0))
    }
  }

  const сходится =
    поПакетам.size === собрано.size &&
    [...собрано].every(([id, штук]) => поПакетам.get(id) === штук)

  return сходится ? (пакеты as Пакет[]) : []
}

/**
 * Одно место из запроса плагина — в несколько, по пакетам склада.
 *
 * пары — товары места, уже разложенные по одной паре (lib/primerka:
 * поПарам), с кодом маркировки и номером «#N» у одинаковых. Номера
 * сквозные по всему заказу, поэтому сначала пары, потом места: в пункте
 * выдачи пару называют по артикулу, и он не должен повториться в двух
 * пакетах.
 *
 * Пару кладём в тот пакет, где лежит её код. Пара без кода идёт в первый
 * пакет, где этого артикула ещё не хватает.
 */
export function разложитьПоМестам(
  место: any,
  пары: any[],
  пакеты: Пакет[],
  артикулСтроки: Map<string, string>
): any[] {
  const нужно = пакеты.map((п) => {
    const поАртикулу = new Map<string, number>()
    const коды = new Set<string>()
    for (const с of п.stroki) {
      const артикул = артикулСтроки.get(с.id)
      if (!артикул) continue
      поАртикулу.set(артикул, (поАртикулу.get(артикул) ?? 0) + с.quantity)
      for (const к of с.kody ?? []) коды.add(к)
    }
    return { поАртикулу, коды }
  })

  const поМестам: any[][] = пакеты.map(() => [])
  const безКода: any[] = []

  const положить = (и: number, пара: any) => {
    const артикул = безНомера(пара.articul)
    поМестам[и].push(пара)
    нужно[и].поАртикулу.set(артикул, (нужно[и].поАртикулу.get(артикул) ?? 0) - 1)
  }

  for (const пара of пары) {
    const и = пара.markCode ? нужно.findIndex((н) => н.коды.has(пара.markCode)) : -1
    if (и >= 0) положить(и, пара)
    else безКода.push(пара)
  }

  for (const пара of безКода) {
    const артикул = безНомера(пара.articul)
    const и = нужно.findIndex((н) => (н.поАртикулу.get(артикул) ?? 0) > 0)
    положить(и >= 0 ? и : 0, пара)
  }

  return поМестам
    .map((товары, и) => ({ товары, пакет: пакеты[и] }))
    .filter(({ товары }) => товары.length)
    .map(({ товары, пакет }, и) => ({
      ...место,
      ...размерыМеста(товары),
      // номер места у нас — по нему потом находим наклейку
      placeNumber: String(пакет.nomer ?? и + 1),
      items: товары,
    }))
}

/**
 * Заказ едет в постамат: в ячейку кладут только одно место. Узнаём по
 * типу пункта (2 у ApiShip), по его названию или по названию тарифа — у
 * СДЭК тарифы в постамат отдельные («Посылка склад-постамат»).
 */
export const этоПостамат = (пункт: any, тариф?: any): boolean => {
  const тип = пункт?.type
  return (
    Number(тип) === 2 ||
    /postamat|постамат/i.test(
      `${тип ?? ""} ${пункт?.name ?? ""} ${тариф?.tariffName ?? ""} ${тариф?.name ?? ""}`
    )
  )
}
