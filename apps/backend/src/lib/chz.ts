/**
 * Проверка кодов маркировки в «Честном знаке» перед чеком «полный расчёт».
 *
 * Зачем. Одежда продаётся в разрешительном режиме (ППРФ 1944): перед
 * продажей код надо проверить в ГИС МТ, а факт и время проверки записать
 * в чек — отраслевой реквизит предмета расчёта (тег 1260, внутри 1262–1265).
 * Без этого Честный знак отмечает «продажу без проверки КМ».
 *
 * Кто проверяет — решает переключатель KASSA_PROVERKA_KM:
 *
 * - chz — проверяем сами, токеном ЧЗ (X-API-KEY), и кладём результат в
 *   sectoral_item_props. Так Атол велел работать, пока у него не готов
 *   ТС ПИоТ (ответ поддержки R1844427, октябрь 2026).
 * - tspiot — проверяет сам Атол через ТС ПИоТ: в чек идут use_tspiot и
 *   permissive_mode, реквизит Атол заполнит сам. Включать, когда Атол
 *   скажет, что ТС ПИоТ к кассе подключён и лицензия ЕСП куплена.
 * - net — не проверяем вовсе. Только для тестов.
 *
 * Не задан — берём tspiot, если ATOL_TSPIOT=true (так было раньше), иначе
 * chz, если есть токен, иначе net.
 *
 * Как говорить с ЧЗ — «Методические рекомендации по реализации запрета
 * продажи…», версия 08 от 15.11.2024 (Оператор-ЦРПТ): список площадок
 * /cdn/info, выбор быстрой по /cdn/health/check, проверка /codes/check.
 * Подробно с источниками — docs/честный-знак-без-тс-пиот.md.
 */

export type Режим = "chz" | "tspiot" | "net"

/** Что ЧЗ сказал про один код (поля из ответа /codes/check). */
export type ОтветПоКоду = {
  cis: string
  valid?: boolean
  printView?: string
  gtin?: string
  verified?: boolean
  found?: boolean
  realizable?: boolean
  utilised?: boolean
  isBlocked?: boolean
  ogvs?: string[]
  isOwner?: boolean
  sold?: boolean
  errorCode?: number
  message?: string
}

export type ПроверкаКода = {
  код: string
  // код без криптохвоста — его можно показывать и писать в журнал
  видимый: string
  reqId: string
  reqTimestamp: number
  запрет: string | null
}

export type ИтогПроверки =
  // все коды можно продавать
  | { вид: "можно"; коды: ПроверкаКода[] }
  // хотя бы один код продавать нельзя — чек не бьём
  | { вид: "нельзя"; коды: ПроверкаКода[] }
  // ЧЗ объявил аварийный режим (HTTP 203): продаём без проверки
  | { вид: "авария" }
  // ЧЗ не ответил, или токен не принят — попробуем позже
  | { вид: "недоступен"; причина: string; токен?: boolean }

const ПУТЬ = "/api/v4/true-api"

// реквизиты документа-основания для тегов 1262–1264 — одинаковы для всех
// товарных групп (методические рекомендации, раздел 3.1)
export const ФОИВ = "030"
export const ДАТА_ОСНОВАНИЯ = "21.11.2023"
export const НОМЕР_ОСНОВАНИЯ = "1944"

const настройки = () => ({
  токен: (process.env.CHZ_TOKEN ?? "").trim(),
  адрес: (process.env.CHZ_URL || "https://cdn.crpt.ru").replace(/\/+$/, ""),
  // заводской номер ФН: по нему ЧЗ при подозрениях заблокирует одну
  // кассу, а не весь токен. Необязателен.
  фн: process.env.CHZ_FN || undefined,
  // у кассы в магазине на ответ 1,5 секунды; у нас покупатель не ждёт,
  // поэтому даём площадке больше
  ждать: Number(process.env.CHZ_TIMEOUT_MS) || 3000,
  // чужой код продать можно по закону, но для нас это ошибка склада:
  // в ЧЗ повиснет расхождение по чужому товару
  толькоСвои: process.env.CHZ_TOLKO_SVOI !== "false",
})

export function режимПроверки(): Режим {
  const явно = process.env.KASSA_PROVERKA_KM
  if (явно === "chz" || явно === "tspiot" || явно === "net") {
    return явно
  }
  if (process.env.ATOL_TSPIOT === "true") {
    return "tspiot"
  }
  return настройки().токен ? "chz" : "net"
}

/** Тег 1260 для одного кода: факт и время проверки из ответа ЧЗ. */
export const отраслевойРеквизит = (reqId: string, reqTimestamp: number) => ({
  federal_id: ФОИВ,
  date: ДАТА_ОСНОВАНИЯ,
  number: НОМЕР_ОСНОВАНИЯ,
  value: `UUID=${reqId}&Time=${reqTimestamp}`,
})

/**
 * Можно ли продавать — по таблице случаев запрета (методические
 * рекомендации, раздел 4). null — можно, иначе причина по-человечески.
 */
export function причинаЗапрета(о: ОтветПоКоду, толькоСвои = настройки().толькоСвои): string | null {
  if (о.found === false || о.errorCode === 10) {
    return "кода нет в Честном знаке"
  }
  if (о.valid === false) {
    return "код считан с ошибкой: неверная структура"
  }
  if (о.verified === false) {
    return "не прошла проверка криптоподписи — код считан не целиком или поддельный"
  }
  if (о.utilised === false) {
    return "по коду нет отчёта о нанесении"
  }
  if (о.isBlocked) {
    return `продажа заблокирована решением госоргана${о.ogvs?.length ? ` (${о.ogvs.join(", ")})` : ""}`
  }
  if (о.sold) {
    return "код уже выведен из оборота — эта вещь числится проданной"
  }
  if (о.realizable === false) {
    return "код не введён в оборот"
  }
  if (о.errorCode) {
    return `Честный знак вернул ошибку ${о.errorCode}${о.message ? `: ${о.message}` : ""}`
  }
  if (толькоСвои && о.isOwner === false) {
    return "код принадлежит другому продавцу, не нашему ИП"
  }
  return null
}

/** Код без криптохвоста: до первого разделителя GS. */
export const видимаяЧасть = (код: string) => код.split("\u001d")[0].slice(0, 31)

// ---------- площадки ----------

type Площадка = { адрес: string; задержка: number }

const ЧАСОВ_6 = 6 * 3600_000
const МИНУТ_15 = 15 * 60_000

let площадки: Площадка[] = []
let площадкиОбновлены = 0
const плохие = new Map<string, number>()

/** Для тестов: забыть площадки. */
export function забытьПлощадки() {
  площадки = []
  площадкиОбновлены = 0
  плохие.clear()
}

class Авария extends Error {}
class ТокенНеПринят extends Error {}

async function запрос(адрес: string, тело?: unknown) {
  const н = настройки()
  const начало = Date.now()
  const ответ = await fetch(адрес, {
    method: тело ? "POST" : "GET",
    headers: { "Content-Type": "application/json; charset=utf-8", "X-API-KEY": н.токен },
    body: тело ? JSON.stringify(тело) : undefined,
    signal: AbortSignal.timeout(н.ждать),
  })
  const д: any = await ответ.json().catch(() => ({}))

  if (ответ.status === 203) {
    throw new Авария()
  }
  if (ответ.status === 401) {
    throw new ТокенНеПринят()
  }

  return { http: ответ.status, д, мс: Date.now() - начало }
}

/**
 * Список площадок, самые быстрые первыми. Обновляем не чаще раза в шесть
 * часов; не отдали новый список — работаем по старому.
 */
async function списокПлощадок(): Promise<Площадка[]> {
  if (площадки.length && Date.now() - площадкиОбновлены < ЧАСОВ_6) {
    return площадки
  }

  const н = настройки()
  let адреса: string[] = []

  try {
    const { http, д } = await запрос(`${н.адрес}${ПУТЬ}/cdn/info`)
    if (http === 200 && д?.code === 0 && Array.isArray(д.hosts)) {
      адреса = д.hosts.map((х: any) => String(х.host ?? "").replace(/\/+$/, "")).filter(Boolean)
    }
  } catch (ошибка) {
    if (ошибка instanceof Авария || ошибка instanceof ТокенНеПринят) {
      throw ошибка
    }
  }

  if (!адреса.length) {
    // список не получили — старый лучше, чем ничего
    return площадки
  }

  const замеры = await Promise.all(
    адреса.map(async (адрес) => {
      try {
        const { http, д, мс } = await запрос(`${адрес}${ПУТЬ}/cdn/health/check`)
        return { адрес, задержка: http === 200 && д?.code === 0 ? мс : Infinity }
      } catch (ошибка) {
        if (ошибка instanceof Авария || ошибка instanceof ТокенНеПринят) {
          throw ошибка
        }
        return { адрес, задержка: Infinity }
      }
    })
  )

  площадки = замеры.sort((а, б) => а.задержка - б.задержка)
  площадкиОбновлены = Date.now()
  плохие.clear()
  return площадки
}

const живые = () => площадки.filter((п) => (плохие.get(п.адрес) ?? 0) < Date.now())

// ---------- проверка ----------

type ОтветПроверки = { reqId: string; reqTimestamp: number; codes: ОтветПоКоду[] }

/**
 * Один запрос /codes/check через лучшую живую площадку. Ошибка сети,
 * 429 или 5xx — повторяем на той же; второй раз — площадку на 15 минут
 * в сторону и идём к следующей.
 */
async function спросить(коды: string[]): Promise<ОтветПроверки> {
  const н = настройки()
  await списокПлощадок()

  let последняя = "площадок нет"

  for (const площадка of живые()) {
    for (let попытка = 0; попытка < 2; попытка++) {
      try {
        const { http, д } = await запрос(`${площадка.адрес}${ПУТЬ}/codes/check`, {
          codes: коды,
          ...(н.фн ? { fiscalDriveNumber: н.фн } : {}),
        })

        if (http === 200 && д?.code === 0 && д.reqId) {
          return { reqId: д.reqId, reqTimestamp: Number(д.reqTimestamp), codes: д.codes ?? [] }
        }

        последняя = `${площадка.адрес} ответила ${http}${д?.description ? `: ${д.description}` : ""}`

        // 5000 — не ответила страна-эмитент; площадка ни при чём, в
        // сторону её не убираем. Повтор не помог — ждём сторожа чеков:
        // продать без проверки, как разрешает методичка, мы не торопимся
        if (д?.code === 5000) {
          if (попытка) {
            throw new Error(последняя)
          }
          continue
        }
        // прочие 4xx — ошибка в запросе, повтор не поможет
        if (http >= 400 && http < 500 && http !== 429) {
          throw new Error(последняя)
        }
      } catch (ошибка: any) {
        if (ошибка instanceof Авария || ошибка instanceof ТокенНеПринят) {
          throw ошибка
        }
        if (ошибка?.message === последняя) {
          throw ошибка
        }
        последняя = `${площадка.адрес}: ${ошибка?.name === "TimeoutError" ? "нет ответа" : ошибка?.message}`
      }
    }

    плохие.set(площадка.адрес, Date.now() + МИНУТ_15)
  }

  if (!живые().length) {
    // все в стороне — в следующий раз запросим список заново
    площадкиОбновлены = 0
  }

  throw new Error(последняя)
}

/**
 * Проверить коды перед продажей. Коды — как отдал сканер, целиком, с
 * разделителями GS и криптохвостом.
 */
export async function проверитьКоды(коды: string[]): Promise<ИтогПроверки> {
  if (!коды.length) {
    return { вид: "можно", коды: [] }
  }
  if (!настройки().токен) {
    return { вид: "недоступен", причина: "не задан CHZ_TOKEN", токен: true }
  }

  const итог: ПроверкаКода[] = []

  try {
    // в одном запросе — коды одного чека; больших чеков у нас не бывает,
    // но лимит ЧЗ на число кодов не опубликован, поэтому режем по 100
    for (let i = 0; i < коды.length; i += 100) {
      const часть = коды.slice(i, i + 100)
      const ответ = await спросить(часть)
      const поКоду = new Map(ответ.codes.map((о) => [о.cis, о]))

      for (const код of часть) {
        const о = поКоду.get(код)
        if (!о) {
          return { вид: "недоступен", причина: `ЧЗ не вернул ответ по коду ${видимаяЧасть(код)}` }
        }
        итог.push({
          код,
          видимый: о.printView ?? видимаяЧасть(код),
          reqId: ответ.reqId,
          reqTimestamp: ответ.reqTimestamp,
          запрет: причинаЗапрета(о),
        })
      }
    }
  } catch (ошибка: any) {
    if (ошибка instanceof Авария) {
      return { вид: "авария" }
    }
    if (ошибка instanceof ТокенНеПринят) {
      return { вид: "недоступен", причина: "Честный знак не принял токен (401) — проверьте CHZ_TOKEN", токен: true }
    }
    return { вид: "недоступен", причина: ошибка?.message ?? "неизвестная ошибка" }
  }

  return { вид: итог.some((к) => к.запрет) ? "нельзя" : "можно", коды: итог }
}
