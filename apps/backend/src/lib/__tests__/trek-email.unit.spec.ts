import { письмоОтправки, названиеСлужбы, текстОтправки } from "../trek-email"

describe("письмо «Заказ отправлен»", () => {
  it("называет службу в скобках", () => {
    const html = письмоОтправки({ номер: "41", служба: названиеСлужбы("cdek"), трек: "123" })
    expect(html).toContain("Заказ 41 передан в доставку (СДЭК).")
  })

  it("без известной службы не пишет «в служба доставки»", () => {
    const html = письмоОтправки({ номер: "41", служба: названиеСлужбы(null), трек: "123" })
    expect(html).toContain("Заказ 41 передан в доставку.")
    expect(html).not.toContain("в служба")
  })

  it("говорит про примерку и в тексте, и в вёрстке", () => {
    const d = { номер: "41", служба: "СДЭК", трек: "123" }
    expect(текстОтправки(d)).toContain("примерочная")
    expect(письмоОтправки(d)).toContain("примерочная")
  })
})
