import { Сторож, ктоПросит } from "../chastota"

describe("сторож частоты писем с кодом", () => {
  it("с одного адреса не больше лимита за окно", () => {
    const с = new Сторож(1000, 2, 10)
    expect(с.пропустить("1.1.1.1", 0)).toBe(0)
    expect(с.пропустить("1.1.1.1", 100)).toBe(0)
    expect(с.пропустить("1.1.1.1", 200)).toBeGreaterThan(0)
    // другой адрес при этом проходит
    expect(с.пропустить("2.2.2.2", 300)).toBe(0)
    // окно прошло: снова можно
    expect(с.пропустить("1.1.1.1", 1101)).toBe(0)
  })

  it("общий предел действует и на обращения без адреса", () => {
    const с = new Сторож(1000, 5, 3)
    expect(с.пропустить("a", 0)).toBe(0)
    expect(с.пропустить("b", 1)).toBe(0)
    expect(с.пропустить("", 2)).toBe(0)
    expect(с.пропустить("c", 3)).toBeGreaterThan(0)
    expect(с.пропустить("", 4)).toBeGreaterThan(0)
  })

  it("отказ не засчитывается как письмо", () => {
    const с = new Сторож(1000, 1, 10)
    expect(с.пропустить("a", 0)).toBe(0)
    for (let т = 1; т < 900; т += 100) expect(с.пропустить("a", т)).toBeGreaterThan(0)
    expect(с.пропустить("a", 1001)).toBe(0)
  })

  it("адрес берём тот, что дописал nginx", () => {
    expect(ктоПросит({ "x-forwarded-for": "9.9.9.9, 1.2.3.4", "x-pokupatel-ip": "5.5.5.5" })).toBe("1.2.3.4")
    expect(ктоПросит({ "x-pokupatel-ip": "::ffff:5.5.5.5" })).toBe("5.5.5.5")
    expect(ктоПросит({})).toBe("")
  })

  it("витрина ходит через nginx с того же сервера: берём адрес покупателя от неё", () => {
    expect(ктоПросит({ "x-forwarded-for": "127.0.0.1", "x-pokupatel-ip": "5.5.5.5" })).toBe("5.5.5.5")
    expect(ктоПросит({ "x-forwarded-for": "::1", "x-pokupatel-ip": "5.5.5.5" })).toBe("5.5.5.5")
    // витрина адреса не знает: считаем только в общий счёт
    expect(ктоПросит({ "x-forwarded-for": "127.0.0.1" })).toBe("")
    expect(ктоПросит({ "x-forwarded-for": "127.0.0.1", "x-pokupatel-ip": "127.0.0.1" })).toBe("")
    // посторонний свой заголовок подставить не может
    expect(ктоПросит({ "x-forwarded-for": "8.8.8.8", "x-pokupatel-ip": "5.5.5.5" })).toBe("8.8.8.8")
  })
})
