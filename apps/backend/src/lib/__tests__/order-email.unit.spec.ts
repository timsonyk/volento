import { доставкаДляПисьма, текстПисьма } from "../order-email"

describe("письмо о заказе: доставка", () => {
  it("пункт выдачи — его название и адрес, а не один город", () => {
    const д = доставкаДляПисьма({
      shipping_address: { city: "Казань", postal_code: null, address_1: "" },
      shipping_methods: [
        {
          name: "Пункт выдачи",
          data: { apishipData: { point: { name: "СДЭК, ул. Баумана", address: "Казань, ул. Баумана, 51" } } },
        },
      ],
    })
    expect(д).toEqual({ способ: "Пункт выдачи, СДЭК, ул. Баумана", адрес: "Казань, ул. Баумана, 51" })
  })

  it("без выбора ApiShip — адрес из заказа, как раньше", () => {
    expect(
      доставкаДляПисьма({
        shipping_address: { city: "Москва", postal_code: "101000", address_1: "Тверская, 1" },
        shipping_methods: [{ name: "Курьер", data: {} }],
      })
    ).toEqual({ способ: "Курьер", адрес: "101000, Москва, Тверская, 1" })
  })

  it("пусто — пусто, без «undefined»", () => {
    expect(доставкаДляПисьма({})).toEqual({ способ: null, адрес: null })
  })

  it("пункт попадает в текст письма", () => {
    const { способ, адрес } = доставкаДляПисьма({
      shipping_methods: [{ name: "Пункт выдачи", data: { apishipData: { point: { address: "Казань, ул. Баумана, 51" } } } }],
    })
    const текст = текстПисьма({
      номер: "№ 7",
      позиции: [],
      товары: "9 999 ₽",
      доставка: "295 ₽",
      итого: "10 294 ₽",
      способДоставки: способ,
      адрес,
    })
    expect(текст).toContain("Адрес: Казань, ул. Баумана, 51")
  })
})
