import { посчитатьПары, сЭтимПокупают } from "../s-etim-pokupayut"

const заказ = (товары: string[], поля: Record<string, unknown> = {}) => ({
  status: "pending",
  metadata: {},
  items: товары.map((product_id) => ({ product_id })),
  ...поля,
})

describe("с этим покупают", () => {
  it("частые соседи первыми", () => {
    const пары = посчитатьПары([
      заказ(["брюки", "юбка"]),
      заказ(["брюки", "жакет"]),
      заказ(["брюки", "юбка", "жакет"]),
      заказ(["брюки", "юбка"]),
    ])
    expect(сЭтимПокупают(пары, "брюки")).toEqual(["юбка", "жакет"])
    expect(сЭтимПокупают(пары, "жакет")).toEqual(["брюки", "юбка"])
  })

  it("два размера одного товара — одна покупка, сам с собой не пара", () => {
    const пары = посчитатьПары([заказ(["брюки", "брюки", "юбка"])])
    expect(сЭтимПокупают(пары, "брюки")).toEqual(["юбка"])
    expect(пары.get("брюки")?.get("юбка")).toBe(1)
  })

  it("отменённые и тестовые заказы склада не считаем", () => {
    const пары = посчитатьПары([
      заказ(["брюки", "юбка"], { status: "canceled" }),
      заказ(["брюки", "жакет"], { metadata: { sklad_test: true } }),
    ])
    expect(сЭтимПокупают(пары, "брюки")).toEqual([])
  })

  it("заказ из одного товара пар не даёт, пустые строки не ломают", () => {
    const пары = посчитатьПары([заказ(["брюки"]), { items: [null, { product_id: null }] }])
    expect(пары.size).toBe(0)
  })

  it("не больше заданного числа", () => {
    const пары = посчитатьПары([заказ(["а", "б", "в", "г"])])
    expect(сЭтимПокупают(пары, "а", 2)).toHaveLength(2)
  })
})
