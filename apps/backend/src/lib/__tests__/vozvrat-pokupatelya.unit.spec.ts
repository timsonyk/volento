import { крайнийСрок, можноВернуть } from "../vozvrat-pokupatelya"

const заказ = (итоги: any, заявки: any[] = []) => ({
  items: [
    { id: "a", title: "Брюки палаццо", variant_title: "46/170", variant_sku: "5986-46/170" },
    { id: "b", title: "Юбка", variant_title: "38", variant_sku: "5110-38" },
  ],
  metadata: { dostavka_itog: итоги, vozvraty_pokupatelya: заявки },
})

const выдан = (когда: string, vykupleno: any[], etap = "gotovo") => ({ kogda: когда, etap, vykupleno, nevykupleno: [] })

describe("возврат через кабинет: срок", () => {
  it("семь дней до конца дня по Москве", () => {
    // получил 21 октября в 23:30 по Москве (20:30 UTC) — вернуть до 28-го, 23:59 МСК
    expect(крайнийСрок("2026-10-21T20:30:00Z").toISOString()).toBe("2026-10-28T20:59:59.999Z")
    // в 01:00 по Москве 22-го (21-го по UTC) — день уже 22-й
    expect(крайнийСрок("2026-10-21T22:00:00Z").toISOString()).toBe("2026-10-29T20:59:59.999Z")
  })
})

describe("возврат через кабинет: что можно вернуть", () => {
  const сейчас = new Date("2026-10-25T12:00:00Z")

  it("забранные пары с кодами, пока срок не вышел", () => {
    const м = можноВернуть(
      заказ({ f1: выдан("2026-10-21T10:00:00Z", [{ id: "a", kody: ["k1", "k2"], shtuk: 2 }, { id: "b", kody: ["k3"], shtuk: 1 }]) }),
      сейчас
    )
    expect(м.пары.map((п) => п.kod)).toEqual(["k1", "k2", "k3"])
    expect(м.пары[0]).toMatchObject({ id_stroki: "a", nazvanie: "Брюки палаццо, 46/170", artikul: "5986-46/170" })
    expect(м.до).toBe("2026-10-28T20:59:59.999Z")
  })

  it("срок вышел — ничего, но дату показываем", () => {
    const м = можноВернуть(заказ({ f1: выдан("2026-10-10T10:00:00Z", [{ id: "a", kody: ["k1"], shtuk: 1 }]) }), сейчас)
    expect(м.пары).toEqual([])
    expect(м.до).toBe("2026-10-17T20:59:59.999Z")
  })

  it("пары уже в заявке не предлагаем", () => {
    const м = можноВернуть(
      заказ({ f1: выдан("2026-10-21T10:00:00Z", [{ id: "a", kody: ["k1", "k2"], shtuk: 2 }]) }, [
        { nomer: "1-В1", status: "zhdem", pary: [{ id_stroki: "a", kod: "k1" }] },
      ]),
      сейчас
    )
    expect(м.пары.map((п) => п.kod)).toEqual(["k2"])
  })

  it("итог ещё не подведён или ничего не забрали — нечего вернуть", () => {
    expect(можноВернуть(заказ({ f1: выдан("2026-10-21T10:00:00Z", [{ id: "a", kody: ["k1"], shtuk: 1 }], "chek") }), сейчас).пары).toEqual([])
    expect(можноВернуть(заказ({ f1: выдан("2026-10-21T10:00:00Z", []) }), сейчас).пары).toEqual([])
    expect(можноВернуть(заказ({}), сейчас)).toEqual({ до: null, пары: [] })
  })
})
