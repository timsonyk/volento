/**
 * Позиция склада на нашем языке и обратно.
 *
 * Главный ключ — артикул Озона, тот самый offer_id, которым склад уже
 * пользуется, когда собирает озоновские поставки. У нас он лежит в
 * артикуле варианта один в один: 3147-46/176. Никаких справочников
 * соответствия вести не надо ни нам, ни складу.
 *
 * Если у склада поля лежат порознь — артикул, размер, рост, как Максим
 * описывал 10 августа, — тот же ключ собирается из них по правилу
 * «артикул-размер/рост». Это ровно то, из чего Озон и склеил offer_id.
 */
export type ПозицияСклада = {
  /** артикул Озона целиком: 3147-46/176 */
  artikul?: string
  /** либо порознь: артикул модели, размер, рост */
  model?: string
  razmer?: string
  rost?: string
}

/** Позиция склада → наш артикул варианта. Не хватает данных — null. */
export const вНашАртикул = (п: ПозицияСклада): string | null => {
  const целиком = String(п.artikul ?? "").trim()
  if (целиком) {
    return целиком
  }

  const модель = String(п.model ?? "").trim()
  const размер = String(п.razmer ?? "").trim()
  const рост = String(п.rost ?? "").trim()

  if (!модель || !размер || !рост) {
    return null
  }

  return `${модель}-${размер}/${рост}`
}

/** Наш артикул варианта → части. Не разобрали — отдаём только целое. */
export const наЧасти = (sku: string): Required<ПозицияСклада> | null => {
  const целиком = String(sku ?? "").trim()
  const м = /^(.+)-([^-/]+)\/([^-/]+)$/.exec(целиком)

  if (!м) {
    return null
  }

  return { artikul: целиком, model: м[1], razmer: м[2], rost: м[3] }
}

/**
 * Сколько физически записать себе, когда склад сказал «доступно N».
 *
 * Склад присылает то же число, что отдаёт Озону и Вайлдберризу:
 * сколько пар он готов продать прямо сейчас. Свои брони под наши же
 * заказы он из него уже вычел — он списывает их у себя, как только
 * заказ увидел.
 *
 * А Medusa вычитает наши брони ещё раз, сама: у неё физический остаток
 * и резерв лежат порознь, и витрина показывает разницу. То же самое
 * вычлось бы дважды, и последняя пара пропадала бы с витрины, хотя
 * лежит на полке и ждёт этого самого заказа.
 *
 * Значит наш физический остаток — это доступное у склада плюс то, что
 * мы сами держим в резерве. Тогда витрина покажет ровно N.
 */
export const физическийОстаток = (
  доступноУСклада: number,
  нашРезерв: number
): number => Math.max(0, Math.trunc(доступноУСклада)) + Math.max(0, нашРезерв)
